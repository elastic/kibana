import * as fs from 'fs';
import * as path from 'path';
import { getKibanaDir } from '../../utils';
import { touchedCriticalFiles } from '../../affected-packages';
import { FTR_CRITICAL_PATHS } from './selective_ftr';

const FTR_CONFIG_TEST_FILES_REL = '.buildkite/ftr_config_test_files.json';

/**
 * Spec->config index generated by `node scripts/ftr_config_test_files`. Maps each
 * enabled FTR config (repo-relative) to the test files it loads. `customRunners`
 * lists enabled configs whose files can't be introspected — their specs are
 * treated as unknown so the consumer falls back to running all FTR.
 */
export interface FtrConfigTestFilesIndex {
  configs: Record<string, string[]>;
  customRunners: string[];
}

/** Reads the committed index, or `null` when it's absent/unreadable (fail open). */
export function loadFtrConfigTestFilesIndex(): FtrConfigTestFilesIndex | null {
  try {
    const raw = fs.readFileSync(path.resolve(getKibanaDir(), FTR_CONFIG_TEST_FILES_REL), 'utf8');
    const parsed = JSON.parse(raw) as Partial<FtrConfigTestFilesIndex>;
    if (!parsed.configs) {
      return null;
    }
    return { configs: parsed.configs, customRunners: parsed.customRunners ?? [] };
  } catch {
    return null;
  }
}

/**
 * Narrow enabled FTR config paths to those that own at least one changed spec.
 *
 * Returns `null` (meaning "don't narrow — run the full set") whenever precise
 * selection isn't provably safe: no index, a critical path changed, or any changed
 * file isn't a known spec (source change, helper, or a spec owned only by a config
 * we couldn't introspect). Only when *every* changed file is a known FTR spec do we
 * return the exact owning configs (intersected with the scheduled set) — so source
 * changes, whose FTR coverage isn't statically knowable, always fall back to full.
 */
export function narrowFtrConfigsToChangedSpecs(
  scheduledConfigPaths: readonly string[],
  changedFiles: readonly string[],
  index: FtrConfigTestFilesIndex | null
): string[] | null {
  if (!index || changedFiles.length === 0) {
    return null;
  }

  if (touchedCriticalFiles([...changedFiles], [...FTR_CRITICAL_PATHS])) {
    return null;
  }

  const specToConfigs = buildSpecToConfigs(index.configs);

  const owningConfigs = new Set<string>();
  for (const file of changedFiles) {
    const configs = specToConfigs.get(file);
    if (!configs) {
      return null; // not a known spec -> can't prove FTR is unaffected, run all
    }
    for (const config of configs) {
      owningConfigs.add(config);
    }
  }

  return scheduledConfigPaths.filter((configPath) => owningConfigs.has(configPath));
}

function buildSpecToConfigs(configs: Record<string, string[]>): Map<string, Set<string>> {
  const specToConfigs = new Map<string, Set<string>>();
  for (const [configPath, testFiles] of Object.entries(configs)) {
    for (const testFile of testFiles) {
      let owners = specToConfigs.get(testFile);
      if (!owners) {
        owners = new Set<string>();
        specToConfigs.set(testFile, owners);
      }
      owners.add(configPath);
    }
  }
  return specToConfigs;
}

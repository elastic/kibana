import { execSync } from 'child_process';
import { existsSync } from 'fs';
import path from 'path';
import { getKibanaDir } from '../utils';
import { filterIgnoredFiles } from './utils';

const REPO_ROOT = getKibanaDir();

const MOON_TIMEOUT_MS = 30000;

/** Resolves `moon`'s absolute path — run via `ts-node`, not yarn, so it's not on `PATH`. */
function getMoonBinPath(): string {
  const moonBinPath = path.resolve(REPO_ROOT, 'node_modules/.bin/moon');
  if (existsSync(moonBinPath)) {
    return moonBinPath;
  }

  return execSync('yarn --silent which moon', { cwd: REPO_ROOT, encoding: 'utf8' }).trim();
}

function queryChangedFiles(
  moonBinPath: string,
  execOptions: Parameters<typeof execSync>[1]
): string[] {
  const output = execSync(`"${moonBinPath}" query changed-files`, execOptions);
  const result = JSON.parse(String(output));

  return Array.isArray(result.files) ? result.files : [];
}

export function getAffectedProjectsMoon(
  mergeBase: string,
  includeDownstream: boolean,
  ignorePatterns: string[] = []
): Set<string> {
  const execOptions = {
    cwd: REPO_ROOT,
    encoding: 'utf8' as const,
    maxBuffer: 30 * 1024 * 1024, // 30MB buffer
  };

  // Mirror the git strategy: recompute the actual merge base instead of trusting `mergeBase` as-is.
  const actualBase = execSync(`git merge-base ${mergeBase} HEAD`, execOptions).trim();

  const moonBinPath = getMoonBinPath();
  const moonExecOptions = {
    ...execOptions,
    timeout: MOON_TIMEOUT_MS,
    env: {
      ...process.env,
      MOON_BASE: actualBase,
      // Without an explicit head, Moon diffs the working tree (including untracked files) rather
      // than the checked-out commit, so files regenerated by earlier CI steps count as changed.
      MOON_HEAD: 'HEAD',
    },
  };

  const downstreamFlag = includeDownstream ? '--downstream deep' : '';
  const command = `"${moonBinPath}" query projects --affected ${downstreamFlag}`;

  // Moon resolves changed files itself, so ignoring paths means handing back a filtered list.
  const filteredFiles =
    ignorePatterns.length > 0
      ? filterIgnoredFiles(queryChangedFiles(moonBinPath, moonExecOptions), ignorePatterns)
      : null;

  const output = execSync(
    command,
    filteredFiles === null
      ? moonExecOptions
      : { ...moonExecOptions, input: JSON.stringify({ files: filteredFiles }) }
  );

  const result = JSON.parse(String(output));

  const packageIds = new Set<string>();
  if (result.projects && Array.isArray(result.projects)) {
    for (const project of result.projects) {
      if (project.id) {
        packageIds.add(project.id);
      }
    }
  }
  return packageIds;
}

#!/usr/bin/env bash
#
# Regenerates the committed workflow step schema and opens (or force-updates) the
# single sync PR that carries it to the target branch. Feature PRs never write the
# artifact, so this is the only writer and concurrent PRs cannot conflict on it.
#
# The target branch is BUILDKITE_BRANCH (set by the on-merge trigger or the schedule).

set -euo pipefail

source .buildkite/scripts/common/util.sh

SCHEMA_CONFIG="src/platform/packages/private/kbn-workflow-step-schema-cli/integration_tests/jest.integration.config.js"
GENERATED_DIR="src/platform/packages/private/kbn-workflow-step-schema-cli/generated"
TARGET_BRANCH="${BUILDKITE_BRANCH:-main}"
PR_TITLE="[One Workflow] Update workflow step schema"
BRANCH_PREFIX="workflow_step_schema_sync"
KIBANA_MACHINE_USERNAME="kibanamachine"

echo "--- Bootstrap Kibana"
export DISABLE_BOOTSTRAP_VALIDATION=false
.buildkite/scripts/bootstrap.sh
.buildkite/scripts/setup_es_snapshot_cache.sh

echo "--- Generate workflow step schema"
run_generation() {
  node scripts/jest_integration --config "$SCHEMA_CONFIG"
}
retry 5 15 run_generation

if [[ -z "$(git status --porcelain --untracked-files=all -- "$GENERATED_DIR")" ]]; then
  echo "The committed workflow step schema is up to date. Nothing to do."
  exit 0
fi

git config --global user.name "$KIBANA_MACHINE_USERNAME"
git config --global user.email '42973632+kibanamachine@users.noreply.github.com'

BRANCH_NAME="${BRANCH_PREFIX}_$(date +%s)"
COMMIT_MESSAGE="$PR_TITLE"

echo "--- Looking for an open sync PR targeting $TARGET_BRANCH"
existing_pr_json="$(gh pr list --repo elastic/kibana --base "$TARGET_BRANCH" --search "$PR_TITLE in:title" \
  --state open --author "$KIBANA_MACHINE_USERNAME" --limit 1 --json number,headRefName,title 2>/dev/null || true)"
existing_pr_title="$(jq -r '.[0].title // empty' <<<"$existing_pr_json")"

git checkout -b "$BRANCH_NAME"
git add -- "$GENERATED_DIR"
git commit -m "$COMMIT_MESSAGE"

if [[ "$existing_pr_title" == "$PR_TITLE" ]]; then
  existing_branch="$(jq -r '.[0].headRefName // empty' <<<"$existing_pr_json")"
  existing_number="$(jq -r '.[0].number // empty' <<<"$existing_pr_json")"
  echo "Open sync PR #$existing_number found (branch: $existing_branch). Force-updating it."
  git push origin "$BRANCH_NAME:$existing_branch" --force
  pr_url="https://github.com/elastic/kibana/pull/$existing_number"
else
  echo "--- Opening a new sync PR (base: $TARGET_BRANCH)"
  git push origin "$BRANCH_NAME"
  pr_url="$(gh pr create --repo elastic/kibana --base "$TARGET_BRANCH" --head "$BRANCH_NAME" \
    --title "$PR_TITLE" \
    --body "Regenerated by $BUILDKITE_BUILD_URL. Feature PRs do not commit this artifact; this PR is the only writer." \
    --label 'release_note:skip' \
    --label 'backport:skip')"
fi

echo "Sync PR: $pr_url"
buildkite-agent annotate "Workflow step schema sync PR: $pr_url" --style info --context workflow-step-schema-sync || true

# A push removes a PR from the merge queue, so (re-)enable auto-merge every time.
if ! gh pr merge --repo elastic/kibana --auto --squash "$pr_url"; then
  echo "^^^ Warning: could not enable auto-merge (squash) for $pr_url"
fi

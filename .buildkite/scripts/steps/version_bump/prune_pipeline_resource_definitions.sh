#!/usr/bin/env bash

set -euo pipefail

source "$(dirname "$0")/versions_json_updates.sh"

echo --- Prune superseded branches from pipeline resource definitions

git fetch origin main
git checkout -B main origin/main

FILES=(
  ".buildkite/pipeline-resource-definitions/kibana-console-definitions-sync.yml"
  ".buildkite/pipeline-resource-definitions/kibana-es-snapshots.yml"
  ".buildkite/pipeline-resource-definitions/kibana-on-merge.yml"
  ".buildkite/pipeline-resource-definitions/kibana-scout-update-metadata.yml"
  ".buildkite/pipeline-resource-definitions/kibana-security-solution-on-merge.yml"
)

prune_superseded_minor_branches "${FILES[@]}"

echo --- Committing pipeline resource definition changes

git config --global user.name kibanamachine
git config --global user.email '42973632+kibanamachine@users.noreply.github.com'

head_branch="prune-pipeline-resource-defs-$(date +%F_%H-%M-%S)"
git checkout -b "$head_branch"
git add "${FILES[@]}"

if git diff --cached --quiet; then
  echo "No changes to commit — no superseded branches in pipeline resource definitions"
  exit 0
fi

git commit -m "[pipeline resource definitions] Remove branches superseded by ${NEW_VERSION}"

git push origin "$head_branch"

prUrl=$(gh pr create --repo elastic/kibana --base main --head "$head_branch" \
  --title "[Auto version bump] $(date +%F) Remove branches superseded by ${NEW_VERSION} from pipeline resource definitions" \
  --body "Generated by $BUILDKITE_BUILD_URL" \
  --label "release_note:skip" --label "backport:skip")
echo "Opened PR: $prUrl"

# Nothing in the build needs this PR merged, and `Fetch DRA Artifacts` waits for this step,
# so enable auto-merge and finish instead of waiting for the merge.
if [ "${DRY_RUN:-}" = "true" ]; then
  echo "DRY_RUN is enabled — skipping auto-merge"
else
  gh pr merge --repo elastic/kibana --auto --squash "$prUrl"
fi

import type { LlmProxy } from '@kbn/ftr-llm-proxy';
import { createToolCallMessage } from '@kbn/ftr-llm-proxy';
import { isTitleGenerationRequest } from '../../common/llm_mocks';

const EMBEDDABLE_ID_PATTERN =
  /platform\.custom_content\.panel_context-([0-9a-f]{8}-(?:[0-9a-f]{4}-){3}[0-9a-f]{12})/;

/**
 * Scripts the agent to update the attached panel. The panel's id is generated by the dashboard, so
 * it is read from the attachment id (`<type>-<embeddableId>`) in the model request instead of being
 * known up front.
 */
export const mockUpdatePanelToolCall = (proxy: LlmProxy, esqlQuery: string) => {
  void proxy.interceptors.userMessage({
    name: 'agent:custom_content_update_panel',
    when: ({ messages }) => !isTitleGenerationRequest(messages),
    response: ({ messages }) => {
      const [, embeddableId] = JSON.stringify(messages).match(EMBEDDABLE_ID_PATTERN) ?? [];
      return createToolCallMessage('custom_content_update_panel', {
        embeddable_id: embeddableId,
        esqlQuery,
      });
    },
  });
};

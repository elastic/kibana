import React, { useEffect, useMemo, useRef, useState } from 'react';
import {
  EuiBadge,
  EuiBasicTable,
  EuiBetaBadge,
  EuiButton,
  EuiFieldSearch,
  EuiFlexGroup,
  EuiFlexItem,
  EuiLink,
  EuiSpacer,
  EuiText,
  type EuiBasicTableColumn,
} from '@elastic/eui';
import { i18n } from '@kbn/i18n';
import { StreamsAppPageTemplate } from '../streams_app_page_template';
import { CreateEntityTypeFlyout } from './create_entity_type_flyout';
import { EditEntityTypeFlyout } from './edit_entity_type_flyout';
import type { FakeEntityType } from './fake_entity_types';
import { FAKE_ENTITY_TYPES } from './fake_entity_types';
import { useStreamsAppParams } from '../../hooks/use_streams_app_params';

type FlyoutState =
  | { kind: 'closed' }
  | { kind: 'create' }
  | { kind: 'edit'; entityType: FakeEntityType };

export const ManageEntityTypesView = () => {
  const {
    query: { edit: editIdFromQuery },
  } = useStreamsAppParams('/manage-entity-types');

  const [flyout, setFlyout] = useState<FlyoutState>({ kind: 'closed' });
  const [search, setSearch] = useState('');

  // Auto-open the edit flyout when the page lands with `?edit=<id>` (e.g.
  // deep-linked from the entity flyout's cog). Tracked with a ref so the
  // user can close the flyout without it immediately reopening from the
  // same query value still hanging around in the URL.
  const consumedEditIdRef = useRef<string | null>(null);
  useEffect(() => {
    if (!editIdFromQuery) return;
    if (consumedEditIdRef.current === editIdFromQuery) return;
    const match = FAKE_ENTITY_TYPES.find((entityType) => entityType.id === editIdFromQuery);
    if (!match) return;
    consumedEditIdRef.current = editIdFromQuery;
    setFlyout({ kind: 'edit', entityType: match });
  }, [editIdFromQuery]);

  const closeFlyout = () => setFlyout({ kind: 'closed' });

  // Lightweight client-side filter: matches against name and category, the
  // two visible identifiers users would naturally search for ("k8s",
  // "service", "kubernetes"). Trimmed + lowercased once per render.
  const filteredEntityTypes = useMemo(() => {
    const query = search.trim().toLowerCase();
    if (!query) return [...FAKE_ENTITY_TYPES];
    return FAKE_ENTITY_TYPES.filter(
      (entityType) =>
        entityType.name.toLowerCase().includes(query) ||
        entityType.category.toLowerCase().includes(query)
    );
  }, [search]);

  const columns = useMemo<Array<EuiBasicTableColumn<FakeEntityType>>>(
    () => [
      {
        field: 'name',
        name: i18n.translate('xpack.streams.entityCentricLab.manage.columns.entityType', {
          defaultMessage: 'Entity type',
        }),
        render: (name: string, row: FakeEntityType) => (
          <EuiLink
            data-test-subj={`entityCentricLabRow-${row.id}`}
            onClick={() => setFlyout({ kind: 'edit', entityType: row })}
          >
            {name}
          </EuiLink>
        ),
      },
      {
        field: 'generatedBy',
        name: i18n.translate('xpack.streams.entityCentricLab.manage.columns.generatedBy', {
          defaultMessage: 'Generated by',
        }),
        render: (generatedBy: FakeEntityType['generatedBy']) => (
          <EuiBadge color={generatedBy === 'Elastic' ? 'hollow' : 'primary'}>
            {generatedBy}
          </EuiBadge>
        ),
      },
      {
        field: 'category',
        name: i18n.translate('xpack.streams.entityCentricLab.manage.columns.category', {
          defaultMessage: 'Category',
        }),
      },
      {
        field: 'entitiesCount',
        name: i18n.translate('xpack.streams.entityCentricLab.manage.columns.entities', {
          defaultMessage: 'Entities',
        }),
        align: 'right',
        width: '120px',
      },
      {
        field: 'subsetsCount',
        name: i18n.translate('xpack.streams.entityCentricLab.manage.columns.subsets', {
          defaultMessage: 'Subsets',
        }),
        align: 'right',
        width: '120px',
      },
    ],
    []
  );

  return (
    <>
      <StreamsAppPageTemplate.Header
        pageTitle={
          <EuiFlexGroup alignItems="center" gutterSize="s" responsive={false}>
            <EuiFlexItem grow={false}>
              {i18n.translate('xpack.streams.entityCentricLab.manage.title', {
                defaultMessage: 'Manage entity types',
              })}
            </EuiFlexItem>
            <EuiFlexItem grow={false}>
              <EuiBetaBadge
                label={i18n.translate('xpack.streams.entityCentricLab.manage.labBadge', {
                  defaultMessage: 'Lab',
                })}
                size="s"
                color="hollow"
              />
            </EuiFlexItem>
          </EuiFlexGroup>
        }
        rightSideItems={[
          <EuiButton
            key="create"
            iconType="plusInCircleFilled"
            onClick={() => setFlyout({ kind: 'create' })}
            data-test-subj="entityCentricLabCreateEntityTypeButton"
          >
            {i18n.translate('xpack.streams.entityCentricLab.manage.createButton', {
              defaultMessage: 'Create new entity type',
            })}
          </EuiButton>,
        ]}
      />
      <StreamsAppPageTemplate.Body>
        <EuiText color="subdued" size="s">
          <p>
            {i18n.translate('xpack.streams.entityCentricLab.manage.subtitle', {
              defaultMessage:
                'Prototype list of entity types. The data is mocked — clicking a row opens a placeholder edit flyout.',
            })}
          </p>
        </EuiText>
        <EuiSpacer size="m" />
        <EuiFieldSearch
          fullWidth
          incremental
          placeholder={i18n.translate('xpack.streams.entityCentricLab.manage.searchPlaceholder', {
            defaultMessage: 'Filter entity types by name or category',
          })}
          value={search}
          onChange={(event) => setSearch(event.target.value)}
          data-test-subj="entityCentricLabManageEntityTypesSearch"
          aria-label={i18n.translate('xpack.streams.entityCentricLab.manage.searchAriaLabel', {
            defaultMessage: 'Filter entity types',
          })}
        />
        <EuiSpacer size="m" />
        <EuiBasicTable<FakeEntityType>
          tableCaption={i18n.translate('xpack.streams.entityCentricLab.manage.tableCaption', {
            defaultMessage: 'Entity types',
          })}
          items={filteredEntityTypes}
          columns={columns}
          rowHeader="name"
          noItemsMessage={i18n.translate('xpack.streams.entityCentricLab.manage.noResults', {
            defaultMessage: 'No entity types match "{query}".',
            values: { query: search.trim() },
          })}
          data-test-subj="entityCentricLabEntityTypesTable"
        />
      </StreamsAppPageTemplate.Body>
      {flyout.kind === 'create' ? <CreateEntityTypeFlyout onClose={closeFlyout} /> : null}
      {flyout.kind === 'edit' ? (
        <EditEntityTypeFlyout entityType={flyout.entityType} onClose={closeFlyout} />
      ) : null}
    </>
  );
};

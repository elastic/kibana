import { i18n } from '@kbn/i18n';
import { z } from '@kbn/zod/v4';
import type { CommonTriggerDefinition } from '@kbn/workflows-extensions/common';
import {
  ConversationAttachmentAddedTriggerId,
  ConversationAttachmentUpdatedTriggerId,
  ConversationAttachmentDeletedTriggerId,
} from '@kbn/agent-builder-common';

const i18nPrefix = 'xpack.agentBuilder.workflowTriggers';

const attachmentEventSourceSchema = z
  .enum(['workflow', 'http_api', 'server_api', 'chat_input', 'execution'])
  .meta({
    description: i18n.translate(`${i18nPrefix}.attachments.eventSchema.source`, {
      defaultMessage:
        'What triggered the change: `workflow` (attachment workflow step), `http_api` (attachment HTTP API), `server_api` (another Kibana plugin using the Agent Builder server-side contract), `chat_input` (attached to a user message), or `execution` (created by the agent during a run). Use this to ignore changes made by your own workflow.',
    }),
  });

const baseAttachmentEventFields = {
  conversationId: z.string().meta({
    description: i18n.translate(`${i18nPrefix}.attachments.eventSchema.conversationId`, {
      defaultMessage: 'The ID of the conversation the attachment belongs to.',
    }),
  }),
  attachmentId: z.string().meta({
    description: i18n.translate(`${i18nPrefix}.attachments.eventSchema.attachmentId`, {
      defaultMessage: 'The ID of the attachment.',
    }),
  }),
  attachmentType: z.string().meta({
    description: i18n.translate(`${i18nPrefix}.attachments.eventSchema.attachmentType`, {
      defaultMessage: 'The attachment type (for example, `text`, `esql`, or `dashboard`).',
    }),
  }),
  source: attachmentEventSourceSchema,
};

const currentVersionField = z.number().meta({
  description: i18n.translate(`${i18nPrefix}.attachments.eventSchema.currentVersion`, {
    defaultMessage: 'The attachment version after this change.',
  }),
});

const attachmentAddedEventSchema = z.object({
  ...baseAttachmentEventFields,
  currentVersion: currentVersionField,
});

const attachmentUpdatedEventSchema = z.object({
  ...baseAttachmentEventFields,
  previousVersion: z.number().meta({
    description: i18n.translate(`${i18nPrefix}.attachments.eventSchema.previousVersion`, {
      defaultMessage: 'The attachment version before this change.',
    }),
  }),
  currentVersion: currentVersionField,
});

const attachmentDeletedEventSchema = z.object({
  ...baseAttachmentEventFields,
  hardDelete: z.boolean().meta({
    description: i18n.translate(`${i18nPrefix}.attachments.eventSchema.hardDelete`, {
      defaultMessage:
        'True when the attachment was permanently removed; false when it was soft-deleted and can be restored.',
    }),
  }),
});

export const attachmentAddedTriggerCommonDefinition: CommonTriggerDefinition = {
  id: ConversationAttachmentAddedTriggerId,
  stability: 'tech_preview',
  eventSchema: attachmentAddedEventSchema,
  title: i18n.translate(`${i18nPrefix}.attachmentAdded.title`, {
    defaultMessage: 'Agent Builder - Attachment added',
  }),
  description: i18n.translate(`${i18nPrefix}.attachmentAdded.description`, {
    defaultMessage: 'Emitted after an attachment is added to a conversation.',
  }),
  documentation: {
    details: i18n.translate(`${i18nPrefix}.attachmentAdded.documentation.details`, {
      defaultMessage:
        'Emitted once the conversation write that added the attachment has been persisted. The payload includes event.conversationId, event.attachmentId, event.attachmentType, event.currentVersion (always 1 for a new attachment), and event.source. Use event.source in trigger conditions to ignore attachments your own workflow added.',
    }),
    examples: [
      `## React to dashboards generated by the agent
\`\`\`yaml
version: '1'
name: Notify on generated dashboard
triggers:
  - type: ${ConversationAttachmentAddedTriggerId}
    on:
      condition: 'event.attachmentType: "dashboard" and event.source: "execution"'
steps:
  - name: notify
    type: console
    with:
      message: Dashboard attached
\`\`\``,
    ],
  },
};

export const attachmentUpdatedTriggerCommonDefinition: CommonTriggerDefinition = {
  id: ConversationAttachmentUpdatedTriggerId,
  stability: 'tech_preview',
  eventSchema: attachmentUpdatedEventSchema,
  title: i18n.translate(`${i18nPrefix}.attachmentUpdated.title`, {
    defaultMessage: 'Agent Builder - Attachment updated',
  }),
  description: i18n.translate(`${i18nPrefix}.attachmentUpdated.description`, {
    defaultMessage: 'Emitted after a new content version of an attachment is stored.',
  }),
  documentation: {
    details: i18n.translate(`${i18nPrefix}.attachmentUpdated.documentation.details`, {
      defaultMessage:
        'Emitted only when the attachment content changes (a new version is created); metadata-only edits do not emit. The payload includes event.conversationId, event.attachmentId, event.attachmentType, event.previousVersion, event.currentVersion, and event.source.',
    }),
    examples: [
      `## Re-run a check when a user edits an attachment
\`\`\`yaml
version: '1'
name: Attachment edited by user
triggers:
  - type: ${ConversationAttachmentUpdatedTriggerId}
    on:
      condition: 'event.source: "http_api" or event.source: "chat_input"'
steps:
  - name: recheck
    type: console
    with:
      message: Attachment content changed
\`\`\``,
    ],
  },
};

export const attachmentDeletedTriggerCommonDefinition: CommonTriggerDefinition = {
  id: ConversationAttachmentDeletedTriggerId,
  stability: 'tech_preview',
  eventSchema: attachmentDeletedEventSchema,
  title: i18n.translate(`${i18nPrefix}.attachmentDeleted.title`, {
    defaultMessage: 'Agent Builder - Attachment deleted',
  }),
  description: i18n.translate(`${i18nPrefix}.attachmentDeleted.description`, {
    defaultMessage: 'Emitted after an attachment is soft-deleted or permanently removed.',
  }),
  documentation: {
    details: i18n.translate(`${i18nPrefix}.attachmentDeleted.documentation.details`, {
      defaultMessage:
        'Emitted once for a soft delete (event.hardDelete: false) and once for a permanent delete of an active attachment (event.hardDelete: true). Purging an already soft-deleted attachment does not emit again. The payload includes event.conversationId, event.attachmentId, event.attachmentType, event.hardDelete, and event.source.',
    }),
    examples: [
      `## Clean up when an attachment is permanently removed
\`\`\`yaml
version: '1'
name: Attachment purged
triggers:
  - type: ${ConversationAttachmentDeletedTriggerId}
    on:
      condition: 'event.hardDelete: true'
steps:
  - name: cleanup
    type: console
    with:
      message: Attachment permanently deleted
\`\`\``,
    ],
  },
};

export const attachmentTriggerCommonDefinitions: CommonTriggerDefinition[] = [
  attachmentAddedTriggerCommonDefinition,
  attachmentUpdatedTriggerCommonDefinition,
  attachmentDeletedTriggerCommonDefinition,
];

import { CONVERSATION_TITLE_MAX_LENGTH } from '@kbn/agent-builder-common';
import { i18n } from '@kbn/i18n';
import { StepCategory } from '@kbn/workflows';
import type { CommonStepDefinition } from '@kbn/workflows-extensions/common';
import { z } from '@kbn/zod/v4';
import {
  ConversationAccessModeSchema,
  ConversationIdSchema,
  ConversationSchema,
} from './conversation_schemas';

export const ConversationCreateStepTypeId = 'conversations.create';

const InputSchema = z.object({
  agent_id: z
    .string()
    .max(1024)
    .optional()
    .describe('The agent to bind the conversation to. Defaults to the default Elastic AI agent.'),
  conversation_id: ConversationIdSchema.optional().describe(
    'Client-supplied conversation ID. Generated by the server when omitted.'
  ),
  title: z
    .string()
    .max(CONVERSATION_TITLE_MAX_LENGTH)
    .optional()
    .describe('Title of the conversation. Defaults to "New conversation".'),
  access_mode: ConversationAccessModeSchema.optional().describe(
    'Who can see the conversation. Defaults to private.'
  ),
});

const OutputSchema = ConversationSchema;

export type ConversationCreateInputSchema = typeof InputSchema;
export type ConversationCreateOutputSchema = typeof OutputSchema;

export const conversationCreateStepCommonDefinition: CommonStepDefinition<
  ConversationCreateInputSchema,
  ConversationCreateOutputSchema
> = {
  id: ConversationCreateStepTypeId,
  category: StepCategory.Ai,
  label: i18n.translate('xpack.agentBuilder.conversationCreateStep.label', {
    defaultMessage: 'Create Conversation',
  }),
  description: i18n.translate('xpack.agentBuilder.conversationCreateStep.description', {
    defaultMessage: 'Create an empty conversation without running an agent.',
  }),
  documentation: {
    details: i18n.translate('xpack.agentBuilder.conversationCreateStep.documentation.details', {
      defaultMessage:
        'Creates an empty conversation owned by the executing user, without triggering an agent execution. Use this when a workflow needs a conversation ID up front — for example to write to it from several later steps. To create a conversation as part of running an agent, use the ai.agent step with create-conversation instead. Creating fails if the supplied ID already exists.',
    }),
    examples: [
      `## Create a conversation and run an agent in it
\`\`\`yaml
- name: create_conversation
  type: ${ConversationCreateStepTypeId}
  with:
    agent_id: "my-custom-agent"
    title: "Triage for {{ inputs.alert_id }}"

- name: investigate
  type: ai.agent
  agent-id: "my-custom-agent"
  with:
    conversation_id: "{{ steps.create_conversation.output.id }}"
    message: "Investigate this alert."
\`\`\``,
      `## Create a conversation the whole team can read
\`\`\`yaml
- name: create_shared_conversation
  type: ${ConversationCreateStepTypeId}
  with:
    title: "Weekly review"
    access_mode: public
\`\`\``,
    ],
  },
  inputSchema: InputSchema,
  outputSchema: OutputSchema,
};

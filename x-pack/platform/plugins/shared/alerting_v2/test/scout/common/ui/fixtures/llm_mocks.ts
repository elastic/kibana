import { last } from 'lodash';
import type { LlmProxy } from '@kbn/ftr-llm-proxy';
import { createToolCallMessage } from '@kbn/ftr-llm-proxy';

const TITLE_GENERATION_PROMPT = 'You are a title-generation utility';

type ProxyMessages = Array<{ role: string; content?: unknown }>;

/** Whether the model request is the conversation title generation, not the agent's own turn. */
export const isTitleGenerationRequest = (messages: ProxyMessages) =>
  String(messages.find((m) => m.role === 'system')?.content ?? '').includes(
    TITLE_GENERATION_PROMPT
  );

/** LLM-facing tool name: Agent Builder replaces `.` with `_` in tool ids. */
export const toLlmToolName = (toolId: string) => toolId.replaceAll('.', '_');

export const mockTitleGeneration = (proxy: LlmProxy, title: string) => {
  void proxy
    .intercept({
      name: 'set_title',
      when: ({ messages }) => isTitleGenerationRequest(messages),
      responseMock: createToolCallMessage('set_title', { title }),
    })
    .completeAfterIntercept();
};

/** Answers the user's message by loading an Agent Builder skill, which unlocks its inline tools. */
export const mockLoadSkill = (proxy: LlmProxy, skill: string) => {
  void proxy.interceptors.userMessage({
    name: `agent:load_skill:${skill}`,
    when: ({ messages }) => !isTitleGenerationRequest(messages),
    response: createToolCallMessage('load_skill', { skill }),
  });
};

/** Answers the next tool result with a tool call. */
export const mockToolResultCall = (
  proxy: LlmProxy,
  interceptorName: string,
  toolName: string,
  toolArg: Record<string, unknown>
) => {
  void proxy.interceptors.toolMessage({
    name: interceptorName,
    when: ({ messages }) => !isTitleGenerationRequest(messages),
    response: createToolCallMessage(toolName, toolArg),
  });
};

/**
 * Ends the round with `answer` followed by a `<render_attachment>` tag. The attachment id is
 * generated by the server, so it is read from `data.<attachmentKey>.id` on the preceding tool
 * result. Without an id the answer is sent without the tag, so the spec fails on the missing card.
 */
export const mockFinalAnswerRenderingAttachment = (
  proxy: LlmProxy,
  answer: string,
  attachmentKey: string
) => {
  const attachmentIdPattern = new RegExp(
    `\\\\?"${attachmentKey}\\\\?"\\s*:\\s*\\{\\s*\\\\?"id\\\\?"\\s*:\\s*\\\\?"([^"\\\\]+)`
  );
  void proxy.interceptors.toolMessage({
    name: `agent:final_answer:${attachmentKey}`,
    when: ({ messages }) => !isTitleGenerationRequest(messages),
    response: ({ messages }) => {
      const toolResult = String(last(messages)?.content ?? '');
      const [, attachmentId] = toolResult.match(attachmentIdPattern) ?? [];
      return attachmentId
        ? `${answer}\n\n<render_attachment id="${attachmentId}" version="1" />`
        : answer;
    },
  });
};

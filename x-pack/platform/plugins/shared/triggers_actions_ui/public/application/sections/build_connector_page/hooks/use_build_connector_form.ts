import { useCallback, useRef, useState } from 'react';
import { i18n } from '@kbn/i18n';
import { useForm } from 'react-hook-form';
import type { UseFormReturn } from 'react-hook-form';
import type { CreateConnectorTypeRequest } from '@kbn/actions-plugin/common';
import type { CreateConnectorTypeError } from '../../../hooks/use_create_connector_type';
import { useCreateConnectorType } from '../../../hooks/use_create_connector_type';
import { useKibana } from '../../../../common/lib/kibana';
import { fetchConnectorTypeLogo } from '../../../lib/action_connector_api';
import { getLogoErrorMessage, isHttpUrl } from '../lib/connector_logo';
import { buildConnectorFormResolver } from '../lib/form_resolver';
import { formDataToRequest, getEmptyFormData, requestToFormData } from '../lib/form_serializers';
import type { BuildConnectorFormData } from '../types';

export interface UseBuildConnectorFormParams {
  /** Called with the new connector type ID after a successful save. */
  onCreated: (connectorTypeId: string) => void;
  /** A definition to start from, e.g. a draft handed off from chat. */
  initialDefinition?: CreateConnectorTypeRequest & { logoUrl?: string };
}

export interface UseBuildConnectorFormReturnValue {
  methods: UseFormReturn<BuildConnectorFormData>;
  isSaving: boolean;
  isSubmitting: boolean;
  createConnectorTypeError: CreateConnectorTypeError | null;
  /** Replaces the form with a definition imported from YAML or generated by the assistant. */
  onApplyDefinition: (
    connectorType: Partial<CreateConnectorTypeRequest> & { logoUrl?: string }
  ) => void;
  /** Validates the form and, if it passes, registers the connector type. */
  submit: () => Promise<void>;
  /** Loads a pending logo URL. Validation can be skipped when saving metadata only. */
  loadPendingLogo: (validateOnError?: boolean) => Promise<boolean>;
}

/** Form state and submit flow of the connector type builder page. */
export const useBuildConnectorForm = ({
  onCreated,
  initialDefinition,
}: UseBuildConnectorFormParams): UseBuildConnectorFormReturnValue => {
  const methods = useForm<BuildConnectorFormData>({
    mode: 'onTouched',
    defaultValues: initialDefinition ? requestToFormData(initialDefinition) : getEmptyFormData(),
    resolver: buildConnectorFormResolver,
  });
  const { http } = useKibana().services;
  const {
    getValues,
    handleSubmit,
    reset,
    setError,
    setValue,
    trigger,
    formState: { isSubmitting: isSubmittingForm },
  } = methods;
  const [isLoadingLogo, setIsLoadingLogo] = useState(false);
  const logoRequestId = useRef(0);
  const {
    isLoading: isSaving,
    createConnectorType,
    createConnectorTypeError,
  } = useCreateConnectorType();

  const onApplyDefinition = useCallback(
    (connectorType: Partial<CreateConnectorTypeRequest> & { logoUrl?: string }) => {
      reset(requestToFormData(connectorType));
      // Surface what the schema would reject right away, so the imported definition can be fixed in place.
      void trigger();
    },
    [reset, trigger]
  );

  const onValid = useCallback(
    async (values: BuildConnectorFormData) => {
      const result = await createConnectorType(formDataToRequest(values));
      if (result) {
        onCreated(result.id);
      }
    },
    [createConnectorType, onCreated]
  );

  // A logo URL that the field has not loaded yet is read here, so saving never needs a separate step.
  const loadPendingLogo = useCallback(
    async (validateOnError = true): Promise<boolean> => {
      const [logoUrl, icon] = getValues(['logoUrl', 'icon']);
      const url = logoUrl.trim();
      if (icon || !url) return true;
      if (!isHttpUrl(url)) {
        if (!validateOnError) {
          setError('logoUrl', {
            type: 'manual',
            message: i18n.translate(
              'xpack.triggersActionsUI.sections.buildConnectorPage.logo.invalidUrl',
              { defaultMessage: 'Enter a valid public image URL.' }
            ),
          });
          return false;
        }
        return true;
      }
      const requestId = ++logoRequestId.current;
      setIsLoadingLogo(true);
      try {
        const { icon: loadedIcon } = await fetchConnectorTypeLogo({ http, url });
        if (requestId !== logoRequestId.current) return false;
        if (getValues('logoUrl').trim() !== url) {
          setError('logoUrl', {
            type: 'manual',
            message: i18n.translate(
              'xpack.triggersActionsUI.sections.buildConnectorPage.logo.changedWhileLoading',
              { defaultMessage: 'The logo URL changed while it was loading. Save again.' }
            ),
          });
          return false;
        }
        setValue('icon', loadedIcon, { shouldDirty: true });
        return true;
      } catch (error) {
        if (requestId !== logoRequestId.current) return false;
        if (getValues('logoUrl').trim() !== url) {
          setError('logoUrl', {
            type: 'manual',
            message: i18n.translate(
              'xpack.triggersActionsUI.sections.buildConnectorPage.logo.changedWhileLoading',
              { defaultMessage: 'The logo URL changed while it was loading. Save again.' }
            ),
          });
          return false;
        }
        setError('logoUrl', { type: 'manual', message: getLogoErrorMessage(error) });
        if (validateOnError) await trigger('logoUrl');
        return false;
      } finally {
        if (requestId === logoRequestId.current) setIsLoadingLogo(false);
      }
    },
    [getValues, http, setError, setValue, trigger]
  );

  const submit = useCallback(async () => {
    if (await loadPendingLogo()) {
      await handleSubmit(onValid)();
    }
  }, [handleSubmit, loadPendingLogo, onValid]);

  const isSubmitting = isSubmittingForm || isLoadingLogo;

  return {
    methods,
    isSaving,
    isSubmitting,
    createConnectorTypeError,
    onApplyDefinition,
    submit,
    loadPendingLogo,
  };
};

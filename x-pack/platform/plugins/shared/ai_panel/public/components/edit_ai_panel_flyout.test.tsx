import React from 'react';
import type { ComponentProps } from 'react';
import { render, screen } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { MockedCodeEditor } from '@kbn/code-editor-mock';
import type { MockedMonacoEditor } from '@kbn/code-editor-mock/monaco_mock';
import { AI_PANEL_CONTEXT_ATTACHMENT_TYPE } from '../../common/panel_context_attachment';

jest.mock('@kbn/code-editor', () => {
  const original = jest.requireActual('@kbn/code-editor');
  return {
    ...original,
    CodeEditor: (props: ComponentProps<typeof MockedMonacoEditor>) => (
      <MockedCodeEditor {...props} />
    ),
  };
});

jest.mock('../hooks/use_edit_flyout_state');
jest.mock('../services');
jest.mock('./esql_preview_section', () => ({
  EsqlPreviewSection: () => <div data-test-subj="mockEsqlPreviewSection" />,
}));

import { useEditFlyoutState } from '../hooks/use_edit_flyout_state';
import { getServices } from '../services';
import { EditAiPanelFlyout } from './edit_ai_panel_flyout';

const mockUseEditFlyoutState = useEditFlyoutState as jest.Mock;

const baseFlyoutState = {
  draftEsqlQuery: '',
  setDraftEsqlQuery: jest.fn(),
  draftTemplate: '',
  setDraftTemplate: jest.fn(),
  detectedTimeField: undefined,
  isAiAvailable: true,
  isPreviewLoading: false,
  previewData: null,
  previewError: null,
  handlePreview: jest.fn(),
};

const setChatConfig = jest.fn();
const clearChatConfig = jest.fn();
const openChat = jest.fn();

const defaultProps = {
  embeddableId: 'panel-1',
  prompt: 'Show KPI cards',
  esqlQuery: undefined as string | undefined,
  template: undefined,
  timeRange: undefined,
  hasGenerationFailed: false,
  onSave: jest.fn(),
  onAgentUpdate: jest.fn(),
  onClose: jest.fn(),
};

beforeEach(() => {
  jest.clearAllMocks();
  mockUseEditFlyoutState.mockReturnValue(baseFlyoutState);
  (getServices as jest.Mock).mockReturnValue({
    agentBuilder: { setChatConfig, clearChatConfig, openChat },
  });
});

describe('EditAiPanelFlyout', () => {
  it('renders the prompt as a disabled field', () => {
    render(<EditAiPanelFlyout {...defaultProps} />);
    expect(screen.getByDisplayValue('Show KPI cards')).toBeDisabled();
  });

  it('shows the AI-generated note', () => {
    render(<EditAiPanelFlyout {...defaultProps} />);
    expect(screen.getByText(/Generated by the AI agent/)).toBeInTheDocument();
  });

  it('does not render the ES|QL preview section for a static panel', () => {
    render(<EditAiPanelFlyout {...defaultProps} />);
    expect(screen.queryByTestId('mockEsqlPreviewSection')).not.toBeInTheDocument();
  });

  it('renders the ES|QL preview section when the panel has a query', () => {
    render(<EditAiPanelFlyout {...defaultProps} esqlQuery="FROM logs" />);
    expect(screen.getByTestId('mockEsqlPreviewSection')).toBeInTheDocument();
  });

  it('shows a "still generating" message in the template section while the template is not ready yet', () => {
    render(<EditAiPanelFlyout {...defaultProps} template={undefined} />);
    expect(screen.getByText(/Still generating/)).toBeInTheDocument();
    expect(screen.queryByTestId('mockedCodeEditor')).not.toBeInTheDocument();
  });

  it('shows the template editor once a template is available', () => {
    mockUseEditFlyoutState.mockReturnValue({ ...baseFlyoutState, draftTemplate: '<p>hi</p>' });
    render(<EditAiPanelFlyout {...defaultProps} template="<p>hi</p>" />);
    expect(screen.queryByText(/Still generating/)).not.toBeInTheDocument();
  });

  it('shows a generation-failed message instead of "still generating" when generation failed', () => {
    render(<EditAiPanelFlyout {...defaultProps} template={undefined} hasGenerationFailed />);
    expect(screen.getByText(/Generation failed/)).toBeInTheDocument();
    expect(screen.queryByText(/Still generating/)).not.toBeInTheDocument();
  });

  describe('refine with agent', () => {
    it('syncs the chat config with the current prompt and query on mount', () => {
      mockUseEditFlyoutState.mockReturnValue({ ...baseFlyoutState, draftEsqlQuery: 'FROM logs' });
      render(<EditAiPanelFlyout {...defaultProps} esqlQuery="FROM logs" />);

      expect(setChatConfig).toHaveBeenCalledWith(
        expect.objectContaining({
          sessionTag: 'ai_panel-panel-1',
          attachments: [expect.objectContaining({ type: AI_PANEL_CONTEXT_ATTACHMENT_TYPE })],
          browserApiTools: [expect.objectContaining({ id: 'update_ai_panel_config' })],
        })
      );
    });

    it('re-syncs the chat config when the draft query changes', () => {
      mockUseEditFlyoutState.mockReturnValue({ ...baseFlyoutState, draftEsqlQuery: 'FROM logs' });
      const { rerender } = render(<EditAiPanelFlyout {...defaultProps} esqlQuery="FROM logs" />);
      expect(setChatConfig).toHaveBeenCalledTimes(1);

      mockUseEditFlyoutState.mockReturnValue({
        ...baseFlyoutState,
        draftEsqlQuery: 'FROM logs | LIMIT 5',
      });
      rerender(<EditAiPanelFlyout {...defaultProps} esqlQuery="FROM logs" />);

      expect(setChatConfig).toHaveBeenCalledTimes(2);
      const lastCall = setChatConfig.mock.calls[1][0];
      expect(lastCall.attachments[0].data.esql_query).toBe('FROM logs | LIMIT 5');
    });

    it('clears the chat config on unmount', () => {
      const { unmount } = render(<EditAiPanelFlyout {...defaultProps} />);
      unmount();
      expect(clearChatConfig).toHaveBeenCalled();
    });

    it('opens the agent chat sidebar and closes the flyout when the button is clicked', async () => {
      const onClose = jest.fn();
      render(<EditAiPanelFlyout {...defaultProps} onClose={onClose} />);
      await userEvent.click(screen.getByRole('button', { name: 'Refine with chat' }));
      expect(openChat).toHaveBeenCalled();
      expect(onClose).toHaveBeenCalled();
    });

    it('does not clear the chat config when closing to open the chat', async () => {
      const onClose = jest.fn();
      const { rerender } = render(<EditAiPanelFlyout {...defaultProps} onClose={onClose} />);
      await userEvent.click(screen.getByRole('button', { name: 'Refine with chat' }));

      // Parent reacts to onClose by unmounting the flyout, same as any other close path.
      rerender(<></>);

      expect(clearChatConfig).not.toHaveBeenCalled();
    });

    it('disables the button when no AI connector is configured', () => {
      mockUseEditFlyoutState.mockReturnValue({ ...baseFlyoutState, isAiAvailable: false });
      render(<EditAiPanelFlyout {...defaultProps} />);
      expect(screen.getByRole('button', { name: 'Refine with chat' })).toBeDisabled();
    });
  });

  describe('save / cancel', () => {
    it('disables Apply and close when nothing has been edited', () => {
      mockUseEditFlyoutState.mockReturnValue({
        ...baseFlyoutState,
        draftEsqlQuery: 'FROM logs',
        draftTemplate: '<p>hi</p>',
      });
      render(<EditAiPanelFlyout {...defaultProps} esqlQuery="FROM logs" template="<p>hi</p>" />);
      expect(screen.getByRole('button', { name: 'Apply and close' })).toBeDisabled();
    });

    it('enables Apply and close once the query differs from the saved one', () => {
      mockUseEditFlyoutState.mockReturnValue({ ...baseFlyoutState, draftEsqlQuery: 'FROM other' });
      render(<EditAiPanelFlyout {...defaultProps} esqlQuery="FROM logs" />);
      expect(screen.getByRole('button', { name: 'Apply and close' })).not.toBeDisabled();
    });

    it('enables Apply and close once the template differs from the saved one', () => {
      mockUseEditFlyoutState.mockReturnValue({
        ...baseFlyoutState,
        draftTemplate: '<p>edited</p>',
      });
      render(<EditAiPanelFlyout {...defaultProps} template="<p>hi</p>" />);
      expect(screen.getByRole('button', { name: 'Apply and close' })).not.toBeDisabled();
    });

    it('calls onSave with the trimmed query and template, then closes', async () => {
      const onSave = jest.fn();
      const onClose = jest.fn();
      mockUseEditFlyoutState.mockReturnValue({
        ...baseFlyoutState,
        draftEsqlQuery: '  FROM logs  ',
        draftTemplate: '  <div></div>  ',
      });
      render(<EditAiPanelFlyout {...defaultProps} onSave={onSave} onClose={onClose} />);

      await userEvent.click(screen.getByRole('button', { name: 'Apply and close' }));

      expect(onSave).toHaveBeenCalledWith('FROM logs', '<div></div>');
      expect(onClose).toHaveBeenCalled();
    });

    it('calls onClose without saving when Cancel is clicked', async () => {
      const onSave = jest.fn();
      const onClose = jest.fn();
      render(<EditAiPanelFlyout {...defaultProps} onSave={onSave} onClose={onClose} />);

      await userEvent.click(screen.getByRole('button', { name: 'Cancel' }));

      expect(onSave).not.toHaveBeenCalled();
      expect(onClose).toHaveBeenCalled();
    });
  });
});

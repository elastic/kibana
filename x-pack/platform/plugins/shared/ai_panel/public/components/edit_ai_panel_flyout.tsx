import {
  EuiAccordion,
  EuiButton,
  EuiButtonEmpty,
  EuiCallOut,
  EuiCopy,
  EuiFlexGroup,
  EuiFlexItem,
  EuiFlyout,
  EuiFlyoutBody,
  EuiFlyoutFooter,
  EuiFlyoutHeader,
  EuiFormRow,
  EuiIcon,
  EuiSpacer,
  EuiText,
  EuiTextArea,
  EuiTitle,
  useEuiTheme,
} from '@elastic/eui';
import { AiButton } from '@kbn/shared-ux-ai-components';
import { css } from '@emotion/react';
import { CodeEditor } from '@kbn/code-editor';
import { i18n } from '@kbn/i18n';
import React, { useEffect, useRef } from 'react';
import { useEditFlyoutState } from '../hooks/use_edit_flyout_state';
import { getServices } from '../services';
import {
  AI_PANEL_REFINE_SESSION_TAG,
  buildAiPanelContextAttachment,
  createUpdateAiPanelConfigTool,
  type UpdateAiPanelConfigParams,
} from '../utils/agent_refine';
import { EsqlPreviewSection } from './esql_preview_section';

export interface EditAiPanelFlyoutProps {
  embeddableId: string;
  prompt: string;
  esqlQuery: string | undefined;
  template: string | undefined;
  timeRange: { from: string; to: string } | undefined;
  hasGenerationFailed: boolean;
  onSave: (esqlQuery: string | undefined, template: string | undefined) => void;
  onAgentUpdate: (params: UpdateAiPanelConfigParams) => void;
  onClose: () => void;
}

export const EditAiPanelFlyout = ({
  embeddableId,
  prompt,
  esqlQuery,
  template,
  timeRange,
  hasGenerationFailed,
  onSave,
  onAgentUpdate,
  onClose,
}: EditAiPanelFlyoutProps) => {
  const { euiTheme } = useEuiTheme();
  const {
    draftEsqlQuery,
    setDraftEsqlQuery,
    draftTemplate,
    setDraftTemplate,
    detectedTimeField,
    isAiAvailable,
    isPreviewLoading,
    previewData,
    previewError,
    handlePreview,
  } = useEditFlyoutState({ esqlQuery, template, timeRange });

  // Skip the unmount cleanup when closing specifically to open the chat, so clearChatConfig()
  // doesn't yank the attachment/tools out from under the session that's opening.
  const keepChatConfigOnCloseRef = useRef(false);

  useEffect(() => {
    const { agentBuilder } = getServices();
    agentBuilder.setChatConfig({
      sessionTag: `${AI_PANEL_REFINE_SESSION_TAG}-${embeddableId}`,
      attachments: [buildAiPanelContextAttachment(prompt, draftEsqlQuery.trim() || undefined)],
      browserApiTools: [createUpdateAiPanelConfigTool(onAgentUpdate)],
    });
    return () => {
      if (!keepChatConfigOnCloseRef.current) {
        getServices().agentBuilder.clearChatConfig();
      }
    };
  }, [embeddableId, prompt, draftEsqlQuery, onAgentUpdate]);

  const handleRefineWithAgent = () => {
    keepChatConfigOnCloseRef.current = true;
    getServices().agentBuilder.openChat();
    onClose();
  };

  return (
    <EuiFlyout
      onClose={onClose}
      size={600}
      type="push"
      resizable
      minWidth={320}
      paddingSize="m"
      aria-labelledby="editAiPanelFlyoutTitle"
    >
      <EuiFlyoutHeader hasBorder>
        <EuiTitle size="s">
          <h2 id="editAiPanelFlyoutTitle">
            {i18n.translate('xpack.aiPanel.editFlyout.title', {
              defaultMessage: 'Edit AI Panel',
            })}
          </h2>
        </EuiTitle>
      </EuiFlyoutHeader>

      <EuiFlyoutBody
        css={css({
          '.euiFlyoutBody__overflowContent': {
            padding: 0,
          },
        })}
      >
        <div css={css({ padding: `${euiTheme.size.base} ${euiTheme.size.base} 0` })}>
          <EuiFormRow
            label={i18n.translate('xpack.aiPanel.editFlyout.panelInstructionsLabel', {
              defaultMessage: 'Panel instructions',
            })}
            labelAppend={
              <EuiCopy textToCopy={prompt}>
                {(copy) => (
                  <EuiButtonEmpty
                    css={{ blockSize: 'auto' }}
                    size="xs"
                    iconType="copy"
                    onClick={copy}
                  >
                    {i18n.translate('xpack.aiPanel.editFlyout.copyLabel', {
                      defaultMessage: 'Copy',
                    })}
                  </EuiButtonEmpty>
                )}
              </EuiCopy>
            }
            fullWidth
          >
            <EuiTextArea value={prompt} disabled rows={5} fullWidth />
          </EuiFormRow>

          <EuiSpacer size="xs" />

          <EuiText size="xs" color="subdued">
            <p>
              {i18n.translate('xpack.aiPanel.editFlyout.agentGeneratedBody', {
                defaultMessage:
                  'Generated by the AI agent from your request. Refine it in chat to regenerate this panel.',
              })}
            </p>
          </EuiText>

          <EuiSpacer size="s" />

          <AiButton
            variant="base"
            iconType="productAgent"
            fullWidth
            onClick={handleRefineWithAgent}
            disabled={isAiAvailable === false}
          >
            {i18n.translate('xpack.aiPanel.editFlyout.refineWithChat', {
              defaultMessage: 'Refine with chat',
            })}
          </AiButton>

          {isAiAvailable === false && (
            <>
              <EuiSpacer size="s" />
              <EuiCallOut
                size="s"
                color="warning"
                iconType="warning"
                title={i18n.translate('xpack.aiPanel.editFlyout.noAiConnector', {
                  defaultMessage:
                    'AI features are not available. Configure an AI connector to enable prompt-based generation.',
                })}
                announceOnMount
              />
            </>
          )}
        </div>

        <EuiSpacer size="l" />

        {esqlQuery && (
          <EsqlPreviewSection
            draftEsqlQuery={draftEsqlQuery}
            onQueryChange={setDraftEsqlQuery}
            detectedTimeField={detectedTimeField}
            isPreviewLoading={isPreviewLoading}
            previewData={previewData}
            previewError={previewError}
            onPreview={handlePreview}
            initialIsOpen={false}
          />
        )}
        <EuiAccordion
          id="editAiPanelTemplateSection"
          borders="horizontal"
          css={css({
            '.euiAccordion__triggerWrapper': {
              paddingInline: euiTheme.size.base,
            },
            '.euiAccordion__children': {
              paddingTop: 0,
            },
          })}
          buttonProps={{ paddingSize: 'm' }}
          buttonContent={
            <EuiFlexGroup alignItems="center" gutterSize="s" responsive={false}>
              <EuiFlexItem grow={false}>
                <EuiIcon type="editorCodeBlock" aria-hidden={true} />
              </EuiFlexItem>
              <EuiFlexItem>
                <EuiText size="s">
                  <strong>
                    {i18n.translate('xpack.aiPanel.editFlyout.templateLabel', {
                      defaultMessage: 'Template (HTML)',
                    })}
                  </strong>
                </EuiText>
              </EuiFlexItem>
            </EuiFlexGroup>
          }
          initialIsOpen={false}
          paddingSize="m"
        >
          {template === undefined && !draftTemplate && hasGenerationFailed ? (
            <EuiText size="s" color="subdued">
              <p>
                {i18n.translate('xpack.aiPanel.editFlyout.templateGenerationFailed', {
                  defaultMessage:
                    "Generation failed, so there's no template yet. Refine the request in chat and try again.",
                })}
              </p>
            </EuiText>
          ) : template === undefined && !draftTemplate ? (
            <EuiText size="s" color="subdued">
              <p>
                {i18n.translate('xpack.aiPanel.editFlyout.templateGenerating', {
                  defaultMessage: 'Still generating — the template will appear here once ready.',
                })}
              </p>
            </EuiText>
          ) : (
            <>
              <EuiCallOut
                announceOnMount
                size="s"
                color="warning"
                title={i18n.translate('xpack.aiPanel.editFlyout.templateWarning', {
                  defaultMessage: 'Editing the template directly may produce unexpected results',
                })}
              />
              <EuiSpacer size="s" />
              <EuiFormRow
                fullWidth
                helpText={i18n.translate('xpack.aiPanel.editFlyout.templateHelp', {
                  defaultMessage:
                    'The HTML template uses Liquid syntax filled with live query data. Changing the prompt will regenerate this template.',
                })}
              >
                <div
                  css={css({
                    height: 400,
                    border: euiTheme.border.thin,
                    borderRadius: euiTheme.border.radius.small,
                  })}
                >
                  <CodeEditor
                    languageId="liquid"
                    value={draftTemplate}
                    onChange={setDraftTemplate}
                    options={{
                      fontSize: 12,
                      minimap: { enabled: false },
                      scrollBeyondLastLine: false,
                      wordWrap: 'on',
                      automaticLayout: true,
                      lineNumbers: 'on',
                      folding: true,
                    }}
                  />
                </div>
              </EuiFormRow>
            </>
          )}
        </EuiAccordion>
      </EuiFlyoutBody>

      <EuiFlyoutFooter>
        <EuiFlexGroup justifyContent="spaceBetween">
          <EuiFlexItem grow={false}>
            <EuiButtonEmpty onClick={onClose}>
              {i18n.translate('xpack.aiPanel.editFlyout.cancel', {
                defaultMessage: 'Cancel',
              })}
            </EuiButtonEmpty>
          </EuiFlexItem>
          <EuiFlexItem grow={false}>
            <EuiButton
              fill
              disabled={draftEsqlQuery === (esqlQuery ?? '') && draftTemplate === (template ?? '')}
              onClick={() => {
                onSave(draftEsqlQuery.trim() || undefined, draftTemplate.trim() || undefined);
                onClose();
              }}
            >
              {i18n.translate('xpack.aiPanel.editFlyout.save', {
                defaultMessage: 'Apply and close',
              })}
            </EuiButton>
          </EuiFlexItem>
        </EuiFlexGroup>
      </EuiFlyoutFooter>
    </EuiFlyout>
  );
};

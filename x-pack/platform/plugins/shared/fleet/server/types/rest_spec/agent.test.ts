describe('GetAgentsRequestSchema', () => {
  it('should allow pagination with less than 10000 agents', () => {
    expect(() =>
      GetAgentsRequestSchema.query.validate({
        page: 500,
        perPage: 20,
      })
    ).not.toThrow();
  });
  it('should not allow pagination to go over 10000 agents', () => {
    expect(() =>
      GetAgentsRequestSchema.query.validate({
        page: 501,
        perPage: 20,
      })
    ).toThrow(/You cannot use page and perPage page over 10000 agents/);
  });
});

describe('bulk action request schemas validate the `agents` KQL string', () => {
  const bulkSchemas: Array<
    [string, { body: { validate: (value: unknown) => void } }, Record<string, unknown>]
  > = [
    ['PostBulkAgentUnenrollRequestSchema', PostBulkAgentUnenrollRequestSchema, {}],
    ['PostBulkRemoveCollectorsRequestSchema', PostBulkRemoveCollectorsRequestSchema, {}],
    ['PostBulkAgentUpgradeRequestSchema', PostBulkAgentUpgradeRequestSchema, { version: '9.5.1' }],
    [
      'PostBulkRequestDiagnosticsActionRequestSchema',
      PostBulkRequestDiagnosticsActionRequestSchema,
      {},
    ],
    [
      'PostBulkAgentReassignRequestSchema',
      PostBulkAgentReassignRequestSchema,
      { policy_id: 'policy-1' },
    ],
    [
      'BulkMigrateAgentsRequestSchema',
      BulkMigrateAgentsRequestSchema,
      { uri: 'http://example.com', enrollment_token: 'token-1' },
    ],
    ['PostBulkUpdateAgentTagsRequestSchema', PostBulkUpdateAgentTagsRequestSchema, {}],
    [
      'BulkChangeAgentsPrivilegeLevelRequestSchema',
      BulkChangeAgentsPrivilegeLevelRequestSchema,
      {},
    ],
    ['PostBulkAgentRollbackRequestSchema', PostBulkAgentRollbackRequestSchema, {}],
    ['PostBulkAgentRestartRequestSchema', PostBulkAgentRestartRequestSchema, {}],
  ];

  it.each(bulkSchemas)('%s rejects fields outside the agent mappings', (_name, schema, extra) => {
    expect(() => schema.body.validate({ agents: 'default_api_key:d*', ...extra })).toThrow(
      /not allowed/
    );
    expect(() => schema.body.validate({ agents: 'access_api_key:d*', ...extra })).toThrow(
      /not allowed/
    );
  });

  it.each(bulkSchemas)('%s still allows a valid KQL string', (_name, schema, extra) => {
    expect(() => schema.body.validate({ agents: 'status:online', ...extra })).not.toThrow();
  });

  it.each(bulkSchemas)('%s still allows an array of agent ids', (_name, schema, extra) => {
    expect(() => schema.body.validate({ agents: ['agent-1', 'agent-2'], ...extra })).not.toThrow();
  });

  const kueryOfLength = (length: number) => `status:${'a'.repeat(length - 'status:'.length)}`;

  it.each(bulkSchemas)('%s allows a KQL string at the maximum length', (_name, schema, extra) => {
    expect(() =>
      schema.body.validate({ agents: kueryOfLength(AGENTS_KUERY_MAX_LENGTH), ...extra })
    ).not.toThrow();
  });

  it.each(bulkSchemas)(
    '%s rejects a KQL string over the maximum length',
    (_name, schema, extra) => {
      expect(() =>
        schema.body.validate({ agents: kueryOfLength(AGENTS_KUERY_MAX_LENGTH + 1), ...extra })
      ).toThrow();
    }
  );

  it('allows the "select all" query generated by the Fleet UI with the maximum number of excluded agents', () => {
    const excludedAgentIds = Array.from(
      { length: SO_SEARCH_LIMIT },
      (_, index) => `"00000000-0000-0000-0000-${String(index).padStart(12, '0')}"`
    );
    const agents = `(status:online) AND NOT (${AGENTS_PREFIX}.agent.id : (${excludedAgentIds.join(
      ' or '
    )}))`;

    expect(() => PostBulkAgentUnenrollRequestSchema.body.validate({ agents })).not.toThrow();
  });

  it.each(bulkSchemas)('%s rejects an agent id over the maximum length', (_name, schema, extra) => {
    expect(() =>
      schema.body.validate({ agents: ['a'.repeat(AGENT_ID_MAX_LENGTH + 1)], ...extra })
    ).toThrow();
  });

  it('rejects fields outside the agent mappings when dryRun is set', () => {
    expect(() =>
      PostBulkRequestDiagnosticsActionRequestSchema.body.validate({
        agents: 'default_api_key:d*',
        dryRun: true,
      })
    ).toThrow(/not allowed/);
  });
});

describe('reporting mode string fields', () => {
  // These fields use the string helpers' warn() mode: overlong input is recorded in the
  // kibana.schema.string_length_violation.length histogram instead of being rejected.
  it.each([10_000, 10_001, 50_000])('accepts a kuery of %i characters', (length) => {
    expect(() =>
      GetAgentsRequestSchema.query.validate({ kuery: 'a'.repeat(length) })
    ).not.toThrow();
  });

  // Regression: the Agents list page builds one kuery from every managed agent policy ID,
  // inlined twice by buildPolicyBaseIdsWithFallbackKuery. At ~124 policies that exceeds
  // 10 000 characters, so a hard limit would 400 the page on load.
  it('accepts the kuery the Agents list page builds for 500 managed policies', () => {
    const ids = Array.from(
      { length: 500 },
      (_, i) => `550e8400-e29b-41d4-a716-${String(i).padStart(12, '0')}`
    );
    const kuery = buildPolicyBaseIdsWithFallbackKuery(
      ids,
      `${AGENTS_PREFIX}.policy_base_id`,
      `${AGENTS_PREFIX}.policy_id`
    );

    expect(kuery.length).toBeGreaterThan(10_000);
    expect(() => GetAgentsRequestSchema.query.validate({ kuery })).not.toThrow();
  });

  it('still applies KQL validation to the kuery field', () => {
    expect(() => GetAgentsRequestSchema.query.validate({ kuery: 'not_a_field: 1' })).toThrow();
  });

  it('accepts an overlong agentId', () => {
    expect(() =>
      GetOneAgentRequestSchema.params.validate({ agentId: 'a'.repeat(1000) })
    ).not.toThrow();
  });

  it('accepts overlong agent tags', () => {
    expect(() =>
      UpdateAgentRequestSchema.body.validate({ tags: ['a'.repeat(1000)] })
    ).not.toThrow();
    expect(() =>
      PostBulkUpdateAgentTagsRequestSchema.body.validate({
        agents: ['agent-1'],
        tagsToAdd: ['a'.repeat(1000)],
        tagsToRemove: ['b'.repeat(1000)],
      })
    ).not.toThrow();
  });

  it('accepts an overlong policy_id in bulk reassign', () => {
    expect(() =>
      PostBulkAgentReassignRequestSchema.body.validate({
        agents: ['agent-1'],
        policy_id: 'a'.repeat(1000),
      })
    ).not.toThrow();
  });
});

describe('PostAgentRestartRequestSchema', () => {
  // This agentId keeps its existing enforced limit rather than reporting mode.
  it('accepts an agentId at exactly 512 characters', () => {
    expect(() =>
      PostAgentRestartRequestSchema.params.validate({ agentId: 'a'.repeat(512) })
    ).not.toThrow();
  });

  it('rejects an agentId over 512 characters', () => {
    expect(() =>
      PostAgentRestartRequestSchema.params.validate({ agentId: 'a'.repeat(513) })
    ).toThrow();
  });
});

import type { JsonDifference } from './round_trip';
import { toFieldPattern } from './round_trip';

export interface RoundTripPanelResult {
  dashboard: string;
  panelId: string;
  title: string | null;
  /** `visualizationType` of the stored Lens state. */
  visualizationType: string | null;
  /** The Lens API `type` the panel converted to. */
  chartType: string | null;
  status: 'compared' | 'missing_after_round_trip' | 'by_reference';
  /** Stored Lens attributes before vs after the round trip, generated IDs aliased. */
  attributes: JsonDifference[];
  /** Panel-level stored config (everything but `attributes`) before vs after. */
  panel: JsonDifference[];
  /** The API config before vs after: whether the API format is stable across a round trip. */
  api: JsonDifference[];
}

export interface RoundTripDashboardResult {
  name: string;
  id: string;
  /** `dropped_panel` warnings from `GET /api/dashboards/{id}`: panels with no as-code schema. */
  dropped: Array<{ panelType: string; message: string }>;
  panels: RoundTripPanelResult[];
}

const MAX_VALUE_LENGTH = 80;

const formatValue = (value: unknown): string => {
  if (value === undefined) {
    return '—';
  }
  const text = JSON.stringify(value);
  const shortened =
    text.length > MAX_VALUE_LENGTH ? `${text.slice(0, MAX_VALUE_LENGTH - 1)}…` : text;
  return `\`${shortened.replace(/\|/g, '\\|').replace(/`/g, "'")}\``;
};

const code = (text: string) => `\`${text.replace(/\|/g, '\\|')}\``;

interface FieldGroup {
  pattern: string;
  kind: JsonDifference['kind'];
  panels: Set<string>;
  chartTypes: Set<string>;
  example: JsonDifference;
}

const groupFields = (
  results: readonly RoundTripPanelResult[],
  pick: (result: RoundTripPanelResult) => JsonDifference[]
): FieldGroup[] => {
  const groups = new Map<string, FieldGroup>();
  for (const result of results) {
    for (const difference of pick(result)) {
      const pattern = toFieldPattern(difference.path);
      const key = `${difference.kind} ${pattern}`;
      const group = groups.get(key) ?? {
        pattern,
        kind: difference.kind,
        panels: new Set<string>(),
        chartTypes: new Set<string>(),
        example: difference,
      };
      group.panels.add(`${result.dashboard}/${result.panelId}`);
      group.chartTypes.add(result.visualizationType ?? result.chartType ?? 'unknown');
      groups.set(key, group);
    }
  }
  return [...groups.values()].sort(
    (a, b) => b.panels.size - a.panels.size || a.pattern.localeCompare(b.pattern)
  );
};

const fieldTable = (groups: FieldGroup[]): string[] =>
  groups.length === 0
    ? ['None.']
    : [
        '| Field | Change | Panels | Chart types | Example before | Example after |',
        '| --- | --- | --- | --- | --- | --- |',
        ...groups.map(
          ({ pattern, kind, panels, chartTypes, example }) =>
            `| ${code(pattern)} | ${kind} | ${panels.size} | ${[...chartTypes]
              .sort()
              .join(', ')} | ${formatValue(example.before)} | ${formatValue(example.after)} |`
        ),
      ];

const differenceList = (label: string, differences: JsonDifference[]): string[] =>
  differences.length === 0
    ? []
    : [
        `- ${label}:`,
        ...differences.map(
          ({ path, kind, before, after }) =>
            `  - ${code(path)} ${kind}: ${formatValue(before)} → ${formatValue(after)}`
        ),
      ];

/** Renders the round-trip results as the Markdown report committed with the corpus. */
export const renderRoundTripReport = (
  dashboards: readonly RoundTripDashboardResult[],
  { kibanaVersion }: { kibanaVersion: string }
): string => {
  const results = dashboards.flatMap(({ panels }) => panels);
  const compared = results.filter(({ status }) => status === 'compared');

  const lines = [
    '# Lens round trip on the sample dashboards',
    '',
    `Generated by the \`round trip\` tests in \`x-pack/platform/test/isomer_corpus\`, against Kibana ${kibanaVersion}. Do not edit by hand.`,
    '',
    'For each Lens panel of each sample overview dashboard:',
    '',
    '1. **Stored state:** `GET /internal/dashboards/app/{id}` returns each Lens panel as migrated, reference-injected stored state (`attributes`), because `lens.apiFormat` is off.',
    '2. **API config:** `GET /api/dashboards/{id}` returns the same panel in the Lens API format (`transformDashboardOut`, then Lens `transformOut` and `toAPIFormat`).',
    '3. **Round trip:** the API dashboard is written back as a copy with `PUT /api/dashboards/{copy}` (Lens `transformIn` and `fromAPIFormat`), then both reads are repeated for the copy.',
    '',
    'Stored attributes are compared after replacing generated layer and column IDs with stable aliases (`<layer_0:count(___records___)>`). String arrays compare as sets, and a key that is missing on one side and empty on the other is not a difference. A **removed** field is stored state the API format does not carry; **changed** and **added** fields are values the round trip rewrites or fills in with defaults.',
    '',
    '## Summary',
    '',
    '| Dashboard | Lens panels | Stored state differs | API config differs after round trip | Dropped (no as-code schema) |',
    '| --- | --- | --- | --- | --- |',
    ...dashboards.map(({ name, panels, dropped }) => {
      const lens = panels.filter(({ status }) => status === 'compared');
      const differs = lens.filter(
        ({ attributes, panel }) => attributes.length + panel.length > 0
      ).length;
      const apiDiffers = lens.filter(({ api }) => api.length > 0).length;
      const droppedTypes = dropped.map(({ panelType }) => panelType);
      return `| ${name} | ${lens.length} | ${differs} | ${apiDiffers} | ${
        droppedTypes.length ? droppedTypes.join(', ') : 'none'
      } |`;
    }),
    '',
    '## Stored fields that do not round-trip',
    '',
    'Grouped by field across panels, most common first.',
    '',
    '### Removed or changed',
    '',
    'Stored state the API format drops or rewrites. Formula panels also lose the helper columns Lens derives from the formula (`math`, and the operations it references), which Lens rebuilds from the formula text when it loads.',
    '',
    ...fieldTable(
      groupFields(compared, ({ attributes }) => attributes.filter(({ kind }) => kind !== 'added'))
    ),
    '',
    '### Added',
    '',
    'Fields the round trip fills in, usually with Lens defaults.',
    '',
    ...fieldTable(
      groupFields(compared, ({ attributes }) => attributes.filter(({ kind }) => kind === 'added'))
    ),
    '',
    '## Panel fields that do not round-trip',
    '',
    'Panel-level state outside `attributes` (titles, time range, drilldowns).',
    '',
    ...fieldTable(groupFields(compared, ({ panel }) => panel)),
    '',
    '## API config differences after a round trip',
    '',
    'The API config of the copy vs the original. Anything here means the API format itself is not stable.',
    '',
    ...fieldTable(groupFields(compared, ({ api }) => api)),
    '',
    '## Panels',
    '',
  ];

  for (const { name, panels } of dashboards) {
    lines.push(`### ${name}`, '');
    for (const result of panels) {
      const heading = `- **${result.title ?? '(untitled)'}** (${code(result.panelId)}, ${
        result.visualizationType ?? 'unknown'
      } → ${result.chartType ?? 'unknown'})`;
      if (result.status !== 'compared') {
        lines.push(`${heading}: ${result.status.replace(/_/g, ' ')}`);
        continue;
      }
      const differences = [
        ...differenceList('Stored', result.attributes),
        ...differenceList('Panel', result.panel),
        ...differenceList('API', result.api),
      ];
      lines.push(differences.length ? `${heading}:` : `${heading}: round-trips`);
      lines.push(...differences.map((line) => `  ${line}`));
    }
    lines.push('');
  }

  return `${lines.join('\n').trimEnd()}\n`;
};

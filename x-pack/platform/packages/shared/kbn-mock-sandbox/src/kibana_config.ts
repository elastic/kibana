import fs from 'fs';
import { parse, stringify } from 'yaml';
import type { LocalEsConnection } from './local_es_connector';

export const LOCAL_ES_CONNECTOR_ID = 'mock-sandbox-local-es';

const HEADER = `# Generated by \`node scripts/mock_sandbox.js\` and rewritten on every start. Do not edit.
# Load it after kibana.dev.yml so it wins over any xpack.sandbox settings there:
#   node scripts/kibana --dev -c config/kibana.yml -c config/kibana.dev.yml -c config/kibana.mock_sandbox.yml --no-dev-config
`;

interface MockSandboxKibanaConfigOptions {
  port: number;
  apiKey: string;
  caCertPath: string;
  es?: LocalEsConnection;
}

/** Builds the Kibana settings that point the sandbox plugin (and its ES connector) at the mock. */
export const buildKibanaConfig = ({
  port,
  apiKey,
  caCertPath,
  es,
}: MockSandboxKibanaConfigOptions): Record<string, unknown> => ({
  'xpack.sandbox': {
    enabled: true,
    host: 'localhost',
    port,
    api_key: apiKey,
    ssl: { certificate_authorities: caCertPath },
  },
  ...(es
    ? {
        'xpack.actions.preconfigured': {
          [LOCAL_ES_CONNECTOR_ID]: {
            name: 'Local Elasticsearch (mock sandbox)',
            actionTypeId: '.http',
            exposeConfig: true,
            config: {
              url: es.containerUrl,
              hasAuth: false,
              headers: { 'Content-Type': 'application/json' },
            },
            secrets: { secretHeaders: { Authorization: es.authorization } },
          },
        },
        'xpack.nightshift_investigations.sandbox.telemetry_connector_id': LOCAL_ES_CONNECTOR_ID,
      }
    : {}),
});

/** Writes the generated config file. */
export const writeKibanaConfig = (path: string, config: Record<string, unknown>): void => {
  fs.writeFileSync(path, `${HEADER}\n${stringify(config)}`);
};

/** Reads the connector `Authorization` header from a previously generated file, if any. */
export const readPreviousAuthorization = (path: string): string | undefined => {
  if (!fs.existsSync(path)) return undefined;
  const config = parse(fs.readFileSync(path, 'utf8')) as {
    'xpack.actions.preconfigured'?: Record<
      string,
      { secrets?: { secretHeaders?: { Authorization?: string } } }
    >;
  } | null;
  const authorization =
    config?.['xpack.actions.preconfigured']?.[LOCAL_ES_CONNECTOR_ID]?.secrets?.secretHeaders
      ?.Authorization;
  return authorization?.startsWith('ApiKey ') ? authorization : undefined;
};

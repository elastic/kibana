import { SupportedChartType } from '@kbn/agent-builder-common/tools/tool_result';
import type { AttachmentPanel } from '@kbn/agent-builder-dashboards-common';
import { VEGA_VIS_TYPE } from '@kbn/agent-builder-visualizations-common';
import { LENS_EMBEDDABLE_TYPE } from '@kbn/lens-common';
import { parse as parseHjson } from 'hjson';
import { z, lazySchema } from '@kbn/zod/v4';
import type { PanelResolutionRequestBase } from '../../resolve_panel';
import { defineRequestPanelKind } from '../panel_kind';

/**
 * Lens and Vega visualization panel requests.
 *
 * A new visualization is resolved from a natural-language (or ES|QL) query with
 * `type: 'vis'` (Lens) or `type: 'vega'`; an existing one is placed with `type: 'attachment'`.
 * This module owns the Lens/Vega members of the content union and the vis
 * resolution-request contract. The host provides the resolver that turns these
 * requests into panel content.
 */

/**
 * Request to resolve a Lens or Vega visualization panel from a natural-language /
 * ES|QL query. This is the vis member of the panel resolution union.
 */
export interface VisPanelResolutionRequest extends PanelResolutionRequestBase {
  /** Which engine renders the panel. On edits, it matches the existing panel. */
  type: 'vis' | 'vega';
  /** Natural language description of the desired visualization. */
  nlQuery: string;
  /** Index, alias, or datastream to target; discovered when omitted. */
  index?: string;
  /** Required for new Lens panels; optional for Vega panels and edits. */
  chartType?: SupportedChartType;
  /** ES|QL query to back the visualization; generated when omitted. */
  esql?: string;
  /** Keep the panel's existing ES|QL query and column bindings instead of regenerating them. */
  preserveESQL?: boolean;
  /** Reauthor the presentation from the chart rules instead of applying only the requested changes. */
  applyChartRules?: boolean;
}

const esqlField = lazySchema(() =>
  z
    .string()
    .max(4096)
    .optional()
    .describe(
      '(optional) An ES|QL query generated by the generate_esql tool or pasted by the user. A query you wrote yourself does not qualify, even after running it with execute_esql. Omit this field when composing new visualizations — the tool generates the query from the natural language query. NEVER write or invent an ES|QL query yourself.'
    )
);

const visPanelContentBaseSchema = lazySchema(() =>
  z.object({
    query: z
      .string()
      .max(2048)
      .describe('A natural language query describing the desired visualization.'),
    index: z
      .string()
      .max(256)
      .optional()
      .describe(
        'Exact index, alias, or datastream identified for this panel. Pass it whenever known, because each panel is generated independently without dashboard context. Omit only when the source is unknown and discovery is needed.'
      ),
    esql: esqlField,
    preserveESQL: z
      .boolean()
      .optional()
      .describe(
        '(optional) Set true to keep the existing ES|QL query of the panel instead of regenerating it, e.g. when the edit only changes presentation (title, legend, axes, colors, number formats, thresholds) or chart type. Omit it when the edit changes what the panel measures.'
      ),
  })
);

/** Creates or edits a Lens panel. A new Lens panel requires the caller to choose its chart type. */
export const lensPanelContentSchema = lazySchema(() =>
  visPanelContentBaseSchema.extend({
    type: z.literal('vis').describe('A Lens chart, generated server-side from `query`.'),
    chartType: z
      .nativeEnum(SupportedChartType)
      .optional()
      .describe(
        'The Lens chart type to create. Choose it from the dashboard chart type guidance. Required for new panels. On an existing panel, omit it to keep the chart type, or set it when the request changes the chart family, such as from xy to pie.'
      ),
    applyChartRules: z
      .boolean()
      .optional()
      .describe(
        '(optional) Existing Lens panels only. Set true to apply all presentation defaults, replacing custom styling. Omit it to change only the requested settings. Independent of preserveESQL, so enhancement can accompany a query change.'
      ),
  })
);

/** Creates or edits a Vega panel, which may carry the closest Lens chart type as an authoring hint. */
export const vegaPanelContentSchema = lazySchema(() =>
  visPanelContentBaseSchema.extend({
    type: z.literal('vega').describe('A Vega-Lite chart, generated server-side from `query`.'),
    chartType: z
      .nativeEnum(SupportedChartType)
      .optional()
      .describe(
        '(optional) The closest Lens chart type, used only as an authoring hint. Omit it when no Lens chart type represents the requested Vega-Lite visualization.'
      ),
  })
);

const isEsqlDataSourceCarrier = (carrier: unknown): boolean => {
  const dataSource = (carrier as { data_source?: { type?: unknown } } | null)?.data_source;
  return dataSource?.type === 'esql';
};

/**
 * Whether a Lens panel reads its data through ES|QL. Only those can be edited; other Lens panels
 * (data views, by reference) cannot.
 */
export const isEsqlLensPanel = ({ type, config }: AttachmentPanel): boolean => {
  if (type !== LENS_EMBEDDABLE_TYPE) {
    return false;
  }
  const { layers } = (config ?? {}) as { layers?: unknown };
  return (Array.isArray(layers) ? layers : [config]).some(isEsqlDataSourceCarrier);
};

/** Parses a Vega panel's HJSON (or JSON) spec string; `undefined` when it does not parse. */
export const parseVegaSpec = (spec: unknown): unknown => {
  if (typeof spec !== 'string') {
    return spec;
  }
  try {
    return parseHjson(spec);
  } catch {
    return undefined;
  }
};

const isRecord = (value: unknown): value is Record<string, unknown> =>
  !!value && typeof value === 'object' && !Array.isArray(value);

/** Vega-Lite keys that hold nested views, whose own `data` the Vega author drops. */
const CHILD_VIEW_KEYS = ['spec', 'layer', 'concat', 'hconcat', 'vconcat'] as const;

/** The keys of the ES|QL `url` the Vega author writes: `%type%`, `query`, and `%context%: true`. */
const ESQL_URL_KEYS_EDITS_KEEP = new Set(['%type%', 'query', '%context%']);

const isEsqlUrlEditsKeep = (url: unknown): boolean =>
  isRecord(url) &&
  url['%type%'] === 'esql' &&
  (url['%context%'] === undefined || url['%context%'] === true) &&
  Object.keys(url).every((key) => ESQL_URL_KEYS_EDITS_KEEP.has(key));

const isRootDataEditsKeep = (data: unknown): boolean =>
  data === undefined ||
  (isRecord(data) && Object.keys(data).length === 1 && isEsqlUrlEditsKeep(data.url));

const nestedViewDeclaresData = (view: Record<string, unknown>): boolean =>
  CHILD_VIEW_KEYS.flatMap((key) => [view[key]].flat())
    .filter(isRecord)
    .some((child) => 'data' in child || nestedViewDeclaresData(child));

/**
 * Whether a Vega panel reads data that an edit cannot keep. The Vega author replaces the root
 * `data` with one ES|QL `url` and drops `data` from nested views, so a panel is editable only when
 * its root `data` is absent or just an ES|QL `url` with no options beyond `%context%: true`, and no
 * nested view declares its own `data`. Query DSL, map files, external urls, inline `values`, a
 * `format`, other url options, Vega `data` arrays and nested view sources would be lost. A lookup's `from.data` is kept, so it does not block an edit. A panel whose spec
 * does not parse is blocked too, since its data sources are unknown.
 */
export const readsDataVegaEditsCannotKeep = ({ type, config }: AttachmentPanel): boolean => {
  if (type !== VEGA_VIS_TYPE) {
    return false;
  }
  const spec = parseVegaSpec(config?.spec);
  if (!isRecord(spec)) {
    return true;
  }
  return !isRootDataEditsKeep(spec.data) || nestedViewDeclaresData(spec);
};

export const lensPanelKind = defineRequestPanelKind({
  type: 'vis',
  embeddableType: LENS_EMBEDDABLE_TYPE,
  label: 'Lens',
  selection: {
    priority: 1,
    whenToUse: 'metrics, time series, bar, line, pie, area, and data tables.',
  },
  canEdit: isEsqlLensPanel,
  uneditableDescription: 'Lens panel that is not backed by ES|QL',
  contentSchema: lensPanelContentSchema,
});

export const vegaPanelKind = defineRequestPanelKind({
  type: 'vega',
  embeddableType: VEGA_VIS_TYPE,
  label: 'Vega',
  selection: {
    priority: 2,
    whenToUse:
      'scatter/bubble plots, small multiples/faceting, layered or combination charts, custom encodings, or when the user asks for Vega.',
  },
  canEdit: (panel) => !readsDataVegaEditsCannotKeep(panel),
  uneditableDescription:
    'Vega panel that reads data other than one top-level ES|QL query (such as an Elasticsearch query, a map file, inline values, or several sources)',
  contentSchema: vegaPanelContentSchema,
});

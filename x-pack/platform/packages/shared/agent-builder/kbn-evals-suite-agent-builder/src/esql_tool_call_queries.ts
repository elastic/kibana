import type { EvaluationResult, Evaluator, Example, TaskOutput } from '@kbn/evals';
import { platformCoreTools } from '@kbn/agent-builder-common';

export interface ToolResult {
  type?: string;
  data?: { esql?: unknown };
}

export interface ToolCallStep {
  type?: string;
  tool_id?: string;
  params?: { query?: unknown; target?: { esql?: unknown } };
  results?: readonly ToolResult[];
}

export interface TurnQueries {
  /** Queries written by `generate_esql`, or by `create_visualization` when the agent passed none. */
  generated: string[];
  /** Non-exploratory queries the agent passed to `execute_esql` or as a visualization's `esql`. */
  provided: string[];
  /** The query behind the turn's answer: the last provided query, or else the last generated one. */
  answer?: string;
}

const isString = (value: unknown): value is string => typeof value === 'string' && value !== '';

/** Returns the ES|QL queries in a tool call's results. */
export const getToolResultQueries = (results: readonly ToolResult[] = []): string[] =>
  results.map(({ data }) => data?.esql).filter(isString);

// A FROM or TS query without STATS reads raw documents, which the agent does to inspect fields
// rather than to answer the question.
const isExploratoryQuery = (query: string): boolean =>
  /^\s*(FROM|TS)\b/i.test(query) && !/\bSTATS\b/i.test(query);

/** Collects the ES|QL queries that a conversation turn's tool calls generated and used. */
export const getTurnQueries = (steps: readonly ToolCallStep[]): TurnQueries => {
  const generated: string[] = [];
  const provided: string[] = [];
  const answers: string[] = [];

  for (const { type, tool_id: toolId, params, results } of steps) {
    if (type !== 'tool_call') {
      continue;
    }
    const executedQuery = params?.query;
    const providedEsql = params?.target?.esql;

    if (toolId === platformCoreTools.generateEsql) {
      generated.push(...getToolResultQueries(results));
    } else if (
      toolId === platformCoreTools.executeEsql &&
      isString(executedQuery) &&
      !isExploratoryQuery(executedQuery)
    ) {
      provided.push(executedQuery);
      answers.push(executedQuery);
    } else if (toolId === platformCoreTools.createVisualization) {
      if (isString(providedEsql)) {
        provided.push(providedEsql);
        answers.push(providedEsql);
      } else {
        const visualizationQueries = getToolResultQueries(results);
        generated.push(...visualizationQueries);
        answers.push(...visualizationQueries);
      }
    }
  }

  return { generated, provided, answer: answers.at(-1) ?? generated.at(-1) };
};

// Dropping the PROMQL time options bound to the time range parameters, as for a chart that applies
// its own time range, still reuses the generated query.
const PROMQL_TIME_OPTION = /\b(?:start|end|time)\s*=\s*\?_t(?:start|end)\b/gi;

const normalizeQuery = (query: string): string =>
  query.replace(PROMQL_TIME_OPTION, '').replace(/\s+/g, ' ').trim();

/**
 * Scores the share of queries the agent provided to tools that a tool generated earlier in the
 * conversation, rather than ones the agent wrote or edited itself.
 */
export const createGeneratedQueriesOnlyEvaluator = <
  TExample extends Example,
  TTaskOutput extends TaskOutput
>({
  getQueries,
}: {
  getQueries: (output: TTaskOutput) => {
    generated: readonly string[];
    provided: readonly string[];
    answer?: string;
  };
}): Evaluator<TExample, TTaskOutput> => ({
  name: 'Generated Queries Only',
  kind: 'CODE',
  direction: 'maximize',
  evaluate: async ({ output }): Promise<EvaluationResult> => {
    const { generated, provided, answer } = getQueries(output);
    if (provided.length === 0) {
      return answer
        ? { score: 1, label: 'none-provided', explanation: 'The agent used a generated query' }
        : { score: 0, label: 'no-query', explanation: 'The agent used no query' };
    }

    const generatedQueries = new Set(generated.map(normalizeQuery));
    const selfWritten = provided.filter((query) => !generatedQueries.has(normalizeQuery(query)));
    const score = (provided.length - selfWritten.length) / provided.length;

    return {
      score,
      label: selfWritten.length === 0 ? 'generated' : 'self-written',
      explanation:
        selfWritten.length === 0
          ? 'Every provided query was generated by a tool'
          : `Queries not generated by a tool:\n${selfWritten.join('\n')}`,
    };
  },
});

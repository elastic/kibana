/**
 * Strips the leading Elastic/SSPL/Apache-2.0 license comment block from a
 * source file, if present. Used by the context-noise eval's file-read tool
 * wrapper to A/B whether hiding the header changes agent quality.
 *
 * Rules:
 * - Only strips a *leading* C-style block comment (`/* ... *\/`), optionally
 *   preceded by a shebang or BOM. Comments that follow code are never touched.
 * - Only strips when the block contains one of the recognized copyright
 *   markers, so unrelated banner comments (e.g. "AUTOGENERATED — DO NOT EDIT")
 *   pass through untouched.
 * - Returns the byte offset and line count of what was stripped, so the
 *   caller can preserve the model's view of file positions if it wants to.
 */

const RECOGNIZED_MARKERS = [
  'Copyright Elasticsearch B.V.',
  'Elastic License 2.0',
  'Server Side Public License',
  'Licensed to Elasticsearch B.V.',
  'Licensed under the Apache License, Version 2.0',
] as const;

export interface StripResult {
  readonly content: string;
  readonly stripped: boolean;
  readonly bytesStripped: number;
  readonly linesStripped: number;
}

const LEADING_BLOCK_COMMENT = /^(﻿)?(#![^\n]*\n)?\s*\/\*[\s\S]*?\*\//;

export const stripLicenseHeader = (source: string): StripResult => {
  const match = source.match(LEADING_BLOCK_COMMENT);
  if (!match) {
    return { content: source, stripped: false, bytesStripped: 0, linesStripped: 0 };
  }

  const block = match[0];
  const isLicenseHeader = RECOGNIZED_MARKERS.some((marker) => block.includes(marker));
  if (!isLicenseHeader) {
    return { content: source, stripped: false, bytesStripped: 0, linesStripped: 0 };
  }

  const remainderStart = match[0].length;
  let cursor = remainderStart;
  while (cursor < source.length && (source[cursor] === '\n' || source[cursor] === '\r')) {
    cursor += 1;
  }

  return {
    content: source.slice(cursor),
    stripped: true,
    bytesStripped: cursor,
    linesStripped: source.slice(0, cursor).split('\n').length - 1,
  };
};

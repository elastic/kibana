import { stripLicenseHeader } from './strip_license_header';

const ELASTIC_HEADER = `/*
 * Copyright Elasticsearch B.V. and/or licensed to Elasticsearch B.V. under one
 * or more contributor license agreements. Licensed under the Elastic License
 * 2.0; you may not use this file except in compliance with the Elastic License
 * 2.0.
 */`;

const APACHE_HEADER = `/*
 * Licensed to Elasticsearch B.V. under one or more contributor
 * license agreements. See the NOTICE file distributed with
 * this work for additional information regarding copyright
 * ownership. Licensed under the Apache License, Version 2.0.
 */`;

describe('stripLicenseHeader', () => {
  it('strips an Elastic license header at the top of the file', () => {
    const source = `${ELASTIC_HEADER}\n\nexport const x = 1;\n`;
    const result = stripLicenseHeader(source);
    expect(result.stripped).toBe(true);
    expect(result.content).toBe('export const x = 1;\n');
    expect(result.linesStripped).toBeGreaterThan(5);
  });

  it('strips an Apache 2.0 header at the top of the file', () => {
    const source = `${APACHE_HEADER}\n\nimport x from 'x';\n`;
    const result = stripLicenseHeader(source);
    expect(result.stripped).toBe(true);
    expect(result.content).toBe("import x from 'x';\n");
  });

  it('leaves an unrelated leading block comment alone', () => {
    const source = `/*\n * AUTOGENERATED — do not edit\n */\nexport const x = 1;\n`;
    const result = stripLicenseHeader(source);
    expect(result.stripped).toBe(false);
    expect(result.content).toBe(source);
  });

  it('does not strip a block comment that follows code', () => {
    const source = `import x from 'x';\n\n${ELASTIC_HEADER}\n`;
    const result = stripLicenseHeader(source);
    expect(result.stripped).toBe(false);
    expect(result.content).toBe(source);
  });

  it('tolerates a shebang and a BOM before the header', () => {
    const source = `﻿#!/usr/bin/env node\n${ELASTIC_HEADER}\nconsole.log('hi');\n`;
    const result = stripLicenseHeader(source);
    expect(result.stripped).toBe(true);
    expect(result.content).toBe("console.log('hi');\n");
  });

  it('is a no-op on files without a leading block comment', () => {
    const source = `export const y = 2;\n`;
    const result = stripLicenseHeader(source);
    expect(result.stripped).toBe(false);
    expect(result.content).toBe(source);
    expect(result.bytesStripped).toBe(0);
    expect(result.linesStripped).toBe(0);
  });
});

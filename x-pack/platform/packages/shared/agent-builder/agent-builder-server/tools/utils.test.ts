import {
  NON_INTERACTIVE_DECLINED_REASON,
  ToolResultType,
  isNonInteractiveDeclinedResult,
} from '@kbn/agent-builder-common';
import {
  createErrorResult,
  createNonInteractiveDeclinedResult,
  getToolResultId,
  isToolResultId,
} from './utils';

describe('isToolResultId', () => {
  it('returns true for a result id generated by getToolResultId', () => {
    expect(isToolResultId(getToolResultId())).toBe(true);
  });
});

describe('createNonInteractiveDeclinedResult', () => {
  it('builds an error result tagged as an auto-declined prompt', () => {
    const result = createNonInteractiveDeclinedResult('declined');

    expect(result.type).toBe(ToolResultType.error);
    expect(isToolResultId(result.tool_result_id)).toBe(true);
    expect(result.data).toEqual({
      message: 'declined',
      metadata: { declined_reason: NON_INTERACTIVE_DECLINED_REASON },
    });
    expect(isNonInteractiveDeclinedResult(result)).toBe(true);
  });

  it('keeps the caller metadata next to the tag', () => {
    const result = createNonInteractiveDeclinedResult('declined', { api: 'indices.delete' });

    expect(result.data.metadata).toEqual({
      api: 'indices.delete',
      declined_reason: NON_INTERACTIVE_DECLINED_REASON,
    });
  });

  it('is the only error result the declined guard recognises', () => {
    expect(isNonInteractiveDeclinedResult(createErrorResult('boom'))).toBe(false);
    expect(
      isNonInteractiveDeclinedResult(
        createErrorResult({ message: 'boom', metadata: { declined_reason: 'user' } })
      )
    ).toBe(false);
  });
});

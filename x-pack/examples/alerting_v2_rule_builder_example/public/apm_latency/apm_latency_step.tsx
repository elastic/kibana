import React, { useEffect, useMemo } from 'react';
import { useFormContext } from 'react-hook-form';
import {
  EuiButtonIcon,
  EuiFieldNumber,
  EuiFieldText,
  EuiFlexGroup,
  EuiFlexItem,
  EuiFormRow,
  EuiSelect,
  EuiSpacer,
  EuiSwitch,
  EuiTitle,
  EuiToolTip,
} from '@elastic/eui';
import {
  useBuilderState,
  type FormValues,
  type RuleBuilderStepProps,
} from '@kbn/alerting-v2-rule-form';
import {
  LATENCY_PERCENTILES,
  generateApmLatencyQuery,
  getGroupingFields,
  type ApmLatencyBuilderFields,
  type LatencyPercentile,
} from '../../common/apm_latency';
import { isApmLatencyFormValid } from './validation';
import {
  ALL_TRANSACTION_TYPES_OPTION,
  ENVIRONMENT_HELP,
  ENVIRONMENT_LABEL,
  GROUP_BY_TRANSACTION_NAME_HELP,
  GROUP_BY_TRANSACTION_NAME_LABEL,
  INDEX_HELP,
  INDEX_LABEL,
  PERCENTILE_LABEL,
  PREVIEW_TOOLTIP,
  SERVICE_NAME_LABEL,
  SERVICE_NAME_PLACEHOLDER,
  STEP_TITLE,
  THRESHOLD_LABEL,
  TIME_FIELD_HELP,
  TIME_FIELD_LABEL,
  TRANSACTION_TYPE_LABEL,
  getPercentileOptionLabel,
} from './translations';

const TRANSACTION_TYPE_OPTIONS = [
  { value: '', text: ALL_TRANSACTION_TYPES_OPTION },
  { value: 'request', text: 'request' },
  { value: 'page-load', text: 'page-load' },
];

const PERCENTILE_OPTIONS = LATENCY_PERCENTILES.map((percentile) => ({
  value: String(percentile),
  text: getPercentileOptionLabel(percentile),
}));

/**
 * Fields of the APM latency builder.
 *
 * The query written to the form is only what the flyout previews and what ES|QL
 * mode would open with — the stored one is regenerated by the server from the
 * same fields, through the very same generator.
 */
export const ApmLatencyStep: React.FC<RuleBuilderStepProps> = ({ state, dispatch }) => {
  const { state: fields, setState: setFields } = useBuilderState<ApmLatencyBuilderFields>();
  const { setValue, watch } = useFormContext<FormValues>();
  const isAlert = watch('kind') === 'alert';

  // Sync time_field to the form immediately so it is never empty when the
  // save request is assembled — the API rejects an empty string.
  useEffect(() => {
    if (fields.timeField) {
      setValue('timeField', fields.timeField);
    }
  }, [fields.timeField, setValue]);

  const generated = useMemo(
    () => (isApmLatencyFormValid(fields) ? generateApmLatencyQuery(fields) : undefined),
    [fields]
  );

  useEffect(() => {
    if (!generated || generated.query.format !== 'composed' || !generated.query.breach) {
      if (state.queryCommitted) {
        dispatch({ type: 'INVALIDATE_QUERY' });
      }
      return;
    }

    const { base, breach, recovery } = generated.query;
    setValue(
      'query',
      isAlert
        ? { format: 'composed', base, breach, ...(recovery ? { recovery } : {}) }
        : { format: 'standalone', breach: { query: `${base}\n${breach.segment}` } }
    );
    setValue('grouping', { fields: getGroupingFields(fields) });

    if (!state.queryCommitted) {
      dispatch({ type: 'COMMIT_QUERY' });
    }
  }, [generated, fields, isAlert, setValue, dispatch, state.queryCommitted]);

  const update = <K extends keyof ApmLatencyBuilderFields>(
    key: K,
    value: ApmLatencyBuilderFields[K]
  ) => setFields({ ...fields, [key]: value });

  return (
    <>
      <EuiFlexGroup justifyContent="spaceBetween" alignItems="center" responsive={false}>
        <EuiFlexItem grow={false}>
          <EuiTitle size="xs">
            <h3>{STEP_TITLE}</h3>
          </EuiTitle>
        </EuiFlexItem>
        <EuiFlexItem grow={false}>
          <EuiToolTip content={PREVIEW_TOOLTIP} disableScreenReaderOutput>
            <EuiButtonIcon
              iconType="inspect"
              aria-label={PREVIEW_TOOLTIP}
              isDisabled={state.childOpen || !generated}
              onClick={() => dispatch({ type: 'OPEN_CHILD_FOR_STEP', step: state.step, isAlert })}
              data-test-subj="apmLatencyOpenPreview"
            />
          </EuiToolTip>
        </EuiFlexItem>
      </EuiFlexGroup>
      <EuiSpacer size="m" />
      <EuiFormRow label={INDEX_LABEL} helpText={INDEX_HELP} fullWidth>
        <EuiFieldText
          fullWidth
          value={fields.index}
          onChange={(e) => update('index', e.target.value)}
          data-test-subj="apmLatencyIndex"
        />
      </EuiFormRow>
      <EuiFormRow label={TIME_FIELD_LABEL} helpText={TIME_FIELD_HELP} fullWidth>
        <EuiFieldText
          fullWidth
          value={fields.timeField}
          onChange={(e) => update('timeField', e.target.value)}
          data-test-subj="apmLatencyTimeField"
        />
      </EuiFormRow>
      <EuiFormRow label={SERVICE_NAME_LABEL} fullWidth>
        <EuiFieldText
          fullWidth
          value={fields.serviceName}
          placeholder={SERVICE_NAME_PLACEHOLDER}
          onChange={(e) => update('serviceName', e.target.value)}
          data-test-subj="apmLatencyServiceName"
        />
      </EuiFormRow>
      <EuiFormRow label={ENVIRONMENT_LABEL} helpText={ENVIRONMENT_HELP} fullWidth>
        <EuiFieldText
          fullWidth
          value={fields.environment ?? ''}
          onChange={(e) => update('environment', e.target.value || undefined)}
          data-test-subj="apmLatencyEnvironment"
        />
      </EuiFormRow>
      <EuiFormRow label={TRANSACTION_TYPE_LABEL} fullWidth>
        <EuiSelect
          fullWidth
          options={TRANSACTION_TYPE_OPTIONS}
          value={fields.transactionType ?? ''}
          onChange={(e) => update('transactionType', e.target.value || undefined)}
          data-test-subj="apmLatencyTransactionType"
        />
      </EuiFormRow>
      <EuiFormRow label={PERCENTILE_LABEL} fullWidth>
        <EuiSelect
          fullWidth
          options={PERCENTILE_OPTIONS}
          value={String(fields.percentile)}
          onChange={(e) => update('percentile', Number(e.target.value) as LatencyPercentile)}
          data-test-subj="apmLatencyPercentile"
        />
      </EuiFormRow>
      <EuiFormRow label={THRESHOLD_LABEL} fullWidth>
        <EuiFieldNumber
          fullWidth
          min={1}
          value={fields.thresholdMs}
          onChange={(e) => update('thresholdMs', Number(e.target.value))}
          data-test-subj="apmLatencyThreshold"
        />
      </EuiFormRow>
      <EuiSpacer size="m" />
      <EuiFormRow helpText={GROUP_BY_TRANSACTION_NAME_HELP} fullWidth>
        <EuiSwitch
          label={GROUP_BY_TRANSACTION_NAME_LABEL}
          checked={fields.groupByTransactionName}
          onChange={(e) => update('groupByTransactionName', e.target.checked)}
          data-test-subj="apmLatencyGroupByTransactionName"
        />
      </EuiFormRow>
    </>
  );
};

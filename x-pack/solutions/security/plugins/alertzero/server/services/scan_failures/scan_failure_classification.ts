/** Definition ids the scan query keeps paging until it has seen, or hits the page cap. */
export const SCAN_FAILURE_DEFINITION_IDS = Object.keys(
  DEFINITION_CLASSIFICATION
) as AlertZeroDefinitionId[];

export const classifyScanFailureDefinition = (
  definitionId: string | null | undefined
): ScanFailureClassification => {
  if (!definitionId || !(definitionId in DEFINITION_CLASSIFICATION)) {
    return unknown;
  }
  return DEFINITION_CLASSIFICATION[definitionId as AlertZeroDefinitionId];
};

/** True when this definition is one of the six catalog Workers, not a child folded onto one. */
export const isCatalogWorkerDefinition = (definitionId: string | null | undefined): boolean => {
  if (!definitionId) {
    return false;
  }
  const classification = classifyScanFailureDefinition(definitionId);
  return classification.kind === 'worker' && classification.workerId === definitionId;
};

type CatalogWorkerId = (typeof SYSTEM_SECURITY_WORKER_CATALOG)[number]['id'];

/**
 * Every AlertZero managed definition. A new id added to one of these install
 * lists without a classification entry fails typecheck.
 */
type AlertZeroDefinitionId =
  | (typeof ALERTZERO_MANAGED_WORKER_WORKFLOW_IDS)[number]
  | (typeof ALERTZERO_RULE_WORKFLOW_IDS)[number]
  | (typeof ALERTZERO_ATTACK_DISCOVERY_WORKFLOW_IDS)[number]
  | (typeof ALERTZERO_FORENSICS_WORKFLOW_IDS)[number]
  | (typeof ALERTZERO_ACTION_WORKFLOW_IDS)[number];

type ScanFailureClassification =
  | { readonly kind: 'worker'; readonly workerId: CatalogWorkerId }
  | { readonly kind: 'exclude' }
  | { readonly kind: 'unknown' };

const worker = (workerId: CatalogWorkerId): ScanFailureClassification => ({
  kind: 'worker',
  workerId,
});

const exclude: ScanFailureClassification = { kind: 'exclude' };
const unknown: ScanFailureClassification = { kind: 'unknown' };


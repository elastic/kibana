import { Annotation } from '@langchain/langgraph';
import type { MigrationTranslationResult } from '../../../../../../../../common/siem_migrations/constants';
import type {
  ElasticRulePartial,
  OriginalRule,
  RuleMigrationRule,
} from '../../../../../../../../common/siem_migrations/model/rule_migration.gen';
import type { RuleSemanticSearchResult } from '../../../../types';

/**
 * One completed, unsuccessful search+match attempt — kept so a retry's semantic-query
 * regeneration can see what's already been tried and avoid repeating it (security-team#18589).
 */
export interface SemanticQueryAttempt {
  query: string;
  candidateNames: string[];
}

/**
 * Max times `searchPrebuiltRuleCandidates` may come back empty before `candidatesRetryRouter`
 * gives up, independent of `MAX_MATCH_ATTEMPTS` below.
 */
export const MAX_SEARCH_ATTEMPTS = 3;

/**
 * Max times `matchPrebuiltRule` may fail to confirm a match before `matchPrebuiltRetryRouter`
 * gives up, independent of `MAX_SEARCH_ATTEMPTS` above. Since each budget is spent
 * independently, the subgraph's worst-case total loop count is
 * `MAX_SEARCH_ATTEMPTS + MAX_MATCH_ATTEMPTS`, not a single shared total.
 */
export const MAX_MATCH_ATTEMPTS = 3;

/** Shared between `searchPrebuiltRuleCandidates` and `matchPrebuiltRule` — both can be the last
 * node to run before the subgraph gives up, depending on whether the final attempt found any
 * candidates at all. */
export const NO_MATCH_SUMMARY =
  '## Prebuilt Rule Matching Summary\nNo related prebuilt rule found.';

export const matchPrebuiltRuleState = Annotation.Root({
  original_rule: Annotation<OriginalRule>(),

  // Splunk is the one falls back to ''
  nl_query: Annotation<string>({
    reducer: (current, value) => value ?? current,
    default: () => '',
  }),
  // The pre-built-rule-specific semantic query for the *current* attempt. Regenerated by
  // createPrebuiltRuleSemanticQuery on every retry, informed by `search_attempts`/`match_attempts` below.
  semantic_query: Annotation<string>({
    reducer: (current, value) => value ?? current,
    default: () => '',
  }),
  // Candidate pre-built rules retrieved for the current attempt's semantic_query.
  candidate_rules: Annotation<RuleSemanticSearchResult[]>({
    reducer: (current, value) => value ?? current,
    default: () => [],
  }),
  // One entry appended per attempt where searchPrebuiltRuleCandidates found zero candidates
  // (candidateNames is always [] here — recorded so createPrebuiltRuleSemanticQuery's retry
  // prompt can see the query didn't even turn up a candidate to consider).
  search_attempts: Annotation<SemanticQueryAttempt[]>({
    reducer: (current, value) => (value ? [...current, ...value] : current),
    default: () => [],
  }),
  // One entry appended per attempt where matchPrebuiltRule had candidates but didn't confirm a
  // match against any of them. Bounded independently of search_attempts, at MAX_MATCH_ATTEMPTS.
  match_attempts: Annotation<SemanticQueryAttempt[]>({
    reducer: (current, value) => (value ? [...current, ...value] : current),
    default: () => [],
  }),
  elastic_rule: Annotation<ElasticRulePartial>({
    reducer: (state, action) => ({ ...state, ...action }),
    default: () => ({} as ElasticRulePartial),
  }),
  translation_result: Annotation<MigrationTranslationResult>(),
  comments: Annotation<RuleMigrationRule['comments']>({
    reducer: (current, value) => (value ? (current ?? []).concat(value) : current),
    default: () => [],
  }),
});

export type MatchPrebuiltRuleState = typeof matchPrebuiltRuleState.State;

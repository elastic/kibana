import type { RequestHandler } from '@kbn/core/server';
import type { TypeOf } from '@kbn/config-schema';
import { EXCLUDE_COLD_AND_FROZEN_TIERS_IN_ANALYZER } from '../../../../../common/constants';
import type { validateEntities } from '../../../../../common/endpoint/schema/resolver';
import type { ResolverEntityIndex } from '../../../../../common/endpoint/types';
import type { SecuritySolutionRequestHandlerContext } from '../../../../types';
import { resolverEntity } from './utils/build_resolver_entity';
import { pickEntityHit } from './utils/pick_entity_hit';
import { createSharedFilters } from '../utils/shared_filters';
import {
  firstProjectQualifiedConcreteIndex,
  stripRemoteIndexPatterns,
  toLocalIndexName,
} from '../utils/index_routing';
import type { GetResolverClusterClient } from '../utils/scoped_client';

// How many `_id` matches to fetch so we can pick the clicked document when the same id exists in
// more than one project. A small bound on a wide search, not a product or deployment limit.
const ENTITY_LOOKUP_SIZE_WHEN_DISAMBIGUATING = 20;

const asIndexArray = (indices: string | string[]): string[] =>
  typeof indices === 'string' ? [indices] : indices;

/**
 * This is used to get an 'entity_id' which is an internal-to-Resolver concept, from an `_id`, which
 * is the artificial ID generated by ES for each document.
 */
export function handleEntities(
  getResolverClient: GetResolverClusterClient
): RequestHandler<
  unknown,
  TypeOf<typeof validateEntities.query>,
  unknown,
  SecuritySolutionRequestHandlerContext
> {
  return async (context, request, response) => {
    const {
      query: { _id, indices },
    } = request;

    const { client, cpsRead } = await getResolverClient(context, request);
    const requestedIndices = asIndexArray(indices);
    const preferredIndex = firstProjectQualifiedConcreteIndex(requestedIndices);
    const searchIndices = stripRemoteIndexPatterns(
      preferredIndex ? [toLocalIndexName(preferredIndex), ...requestedIndices] : requestedIndices,
      cpsRead
    );
    const excludeColdAndFrozenTiers = await (
      await context.core
    ).uiSettings.client.get<boolean>(EXCLUDE_COLD_AND_FROZEN_TIERS_IN_ANALYZER);

    const queryResponse = await client.asCurrentUser.search({
      ignore_unavailable: true,
      index: searchIndices,
      // Fan-out can return the same `_id` from more than one project; fetch enough hits to pick
      // the clicked document when a concrete index was supplied.
      size: preferredIndex ? ENTITY_LOOKUP_SIZE_WHEN_DISAMBIGUATING : 1,
      query: {
        bool: {
          filter: [
            ...createSharedFilters({ excludeColdAndFrozenTiers }),
            {
              ids: {
                values: _id,
              },
            },
          ],
        },
      },
    });

    const matchedHit = pickEntityHit(queryResponse.hits.hits, preferredIndex);
    const responseBody: ResolverEntityIndex = resolverEntity(matchedHit ? [matchedHit] : []);
    return response.ok({ body: responseBody });
  };
}

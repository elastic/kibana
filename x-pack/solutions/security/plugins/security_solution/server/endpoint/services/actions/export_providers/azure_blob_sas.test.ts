import { createAzureBlobServiceSas } from './azure_blob_sas';

const OPTIONS = {
  accountName: 'exportsacct',
  // Not a real key
  accountKey:
    'MDEyMzQ1Njc4OWFiY2RlZjAxMjM0NTY3ODlhYmNkZWYwMTIzNDU2Nzg5YWJjZGVmMDEyMzQ1Njc4OWFiY2RlZg==',
  container: 'exports',
  blobPath: '6f2b0c1e-6a43-4c55-9d0a-2f1b7c3e9a10/upload.zip',
  expiresOn: new Date('2026-12-09T12:00:00.000Z'),
};

describe('createAzureBlobServiceSas()', () => {
  it('matches the SAS generated by @azure/storage-blob 12 generateBlobSASQueryParameters for the same input', () => {
    expect(createAzureBlobServiceSas(OPTIONS)).toBe(
      'sv=2022-11-02&spr=https&se=2026-12-09T12%3A00%3A00Z&sr=b&sp=rcw&sig=85mFaUOCtSTkUsl%2BbhyARzVmRsKZg0Pu0votXPDsR2o%3D'
    );
  });

  it('emits `se` without milliseconds', () => {
    const sas = createAzureBlobServiceSas({
      ...OPTIONS,
      expiresOn: new Date('2026-12-09T12:00:00.789Z'),
    });

    expect(new URLSearchParams(sas).get('se')).toBe('2026-12-09T12:00:00Z');
  });

  it('has no start time and no leading `?`', () => {
    const sas = createAzureBlobServiceSas(OPTIONS);

    expect(sas).not.toMatch(/(^|&)st=/);
    expect(sas.startsWith('?')).toBe(false);
  });
});

import React from 'react';
import { fireEvent, render, screen } from '@testing-library/react';
import { I18nProvider } from '@kbn/i18n-react';
import { AiExplainView } from './ai_explain_view';
import type { AiExplainResult } from './ai_explain';

const result: AiExplainResult = {
  summary: 'A likely lateral-movement chain centered on jump-box-01.',
  assessment: 'Active intrusion at the lateral-movement stage; intent likely persistence.',
  chain: [
    {
      label: 'logged in to jump-box-01',
      severity: 'medium',
      evidence: 'Suspicious sudo Escalation',
    },
    { label: 'escalated via sudo', severity: 'high', evidence: 'T1548' },
  ],
  entities: [
    { name: 'jump-box-01', kind: 'host' },
    { name: 'a.rodriguez', kind: 'user' },
  ],
  tactics: ['Privilege Escalation'],
  actions: [
    {
      label: 'Hunt a.rodriguez for lateral movement',
      action: 'hunt',
      targetName: 'a.rodriguez',
      targetKind: 'user',
      targetTechnique: undefined,
    },
    {
      label: 'Confirm the escalation was authorized',
      action: 'none',
      targetName: undefined,
      targetKind: undefined,
      targetTechnique: undefined,
    },
  ],
  severityRationale: 'Critical because a production host was reached.',
  confidence: 'medium',
};

const baseProps = {
  result: undefined,
  rawResult: undefined,
  isGenerating: false,
  error: undefined,
  hasConnector: true,
  connectorName: 'Azure OpenAI',
  onGenerate: jest.fn(),
  hasRequested: false,
};

const renderView = (props: Partial<React.ComponentProps<typeof AiExplainView>> = {}) =>
  render(
    <I18nProvider>
      <AiExplainView {...baseProps} {...props} />
    </I18nProvider>
  );

describe('AiExplainView', () => {
  it('shows a "no AI connector" state when none is configured', () => {
    renderView({ hasConnector: false });
    expect(screen.getByTestId('aiExplainNoConnector')).toBeInTheDocument();
  });

  it('shows the initial CTA before a request and triggers generation', () => {
    const onGenerate = jest.fn();
    renderView({ onGenerate });
    expect(screen.getByTestId('aiExplainCta')).toBeInTheDocument();
    fireEvent.click(screen.getByTestId('aiExplainGenerate'));
    expect(onGenerate).toHaveBeenCalled();
  });

  it('shows a loading shimmer while generating', () => {
    renderView({ isGenerating: true, hasRequested: true });
    expect(screen.getByTestId('entityIntelligenceShimmer')).toBeInTheDocument();
  });

  it('shows an error state with a retry', () => {
    const onGenerate = jest.fn();
    renderView({ error: 'boom', hasRequested: true, onGenerate });
    expect(screen.getByTestId('aiExplainError')).toBeInTheDocument();
    fireEvent.click(screen.getByText('Retry'));
    expect(onGenerate).toHaveBeenCalled();
  });

  it('renders the rich graphics: summary, assessment, flow, evidence, tactics, entities, confidence', () => {
    renderView({ result, rawResult: 'raw text', hasRequested: true });
    expect(screen.getByTestId('aiExplainView')).toBeInTheDocument();
    expect(
      screen.getByText('A likely lateral-movement chain centered on jump-box-01.')
    ).toBeInTheDocument();
    // Assessment callout.
    expect(screen.getByTestId('aiExplainAssessment')).toHaveTextContent('Active intrusion');
    // Attack-flow steps + per-step evidence.
    const chain = screen.getByTestId('aiExplainChain');
    expect(chain).toHaveTextContent('logged in to jump-box-01');
    expect(chain).toHaveTextContent('Suspicious sudo Escalation');
    // Severity legend for the flow (colors are explained, not decoration).
    expect(screen.getByTestId('aiExplainChainLegend')).toBeInTheDocument();
    // Entity chips.
    const entities = screen.getByTestId('aiExplainEntities');
    expect(entities).toHaveTextContent('jump-box-01');
    expect(entities).toHaveTextContent('a.rodriguez');
    // Tactic chip + rationale + confidence + provenance.
    expect(screen.getByTestId('aiExplainTactics')).toHaveTextContent('Privilege Escalation');
    expect(screen.getByTestId('aiExplainView')).toHaveTextContent('Severity rationale:');
    expect(screen.getByTestId('aiExplainConfidence')).toHaveTextContent('Medium confidence');
    expect(screen.getByText(/Generated by Azure OpenAI/)).toBeInTheDocument();
  });

  it('focuses a graph entity when a key-entity chip is clicked', () => {
    const onEntityClick = jest.fn();
    renderView({ result, rawResult: 'raw', hasRequested: true, onEntityClick });
    fireEvent.click(screen.getByText('a.rodriguez'));
    expect(onEntityClick).toHaveBeenCalledWith({ name: 'a.rodriguez', kind: 'user' });
  });

  it('invokes onStepClick when a progression step is clicked', () => {
    const onStepClick = jest.fn();
    renderView({ result, rawResult: 'raw', hasRequested: true, onStepClick });
    fireEvent.click(screen.getAllByTestId('aiExplainChainStep')[0]);
    expect(onStepClick).toHaveBeenCalledWith(
      expect.objectContaining({ label: 'logged in to jump-box-01' })
    );
  });

  it('runs an actionable next step and leaves static ones inert', () => {
    const onAction = jest.fn();
    renderView({ result, rawResult: 'raw', hasRequested: true, onAction });
    const actionable = screen.getByTestId('aiExplainActionButton');
    fireEvent.click(actionable);
    expect(onAction).toHaveBeenCalledWith(expect.objectContaining({ action: 'hunt' }));
    // The 'none' action renders as a static row and is not clickable-through.
    expect(screen.getByTestId('aiExplainActionStatic')).toBeInTheDocument();
  });

  it('omits sections the model could not support (grounding)', () => {
    renderView({
      result: {
        ...result,
        assessment: undefined,
        chain: [],
        tactics: [],
        actions: [],
        entities: [],
      },
      rawResult: 'raw',
      hasRequested: true,
    });
    expect(screen.queryByTestId('aiExplainAssessment')).not.toBeInTheDocument();
    expect(screen.queryByTestId('aiExplainChain')).not.toBeInTheDocument();
    expect(screen.queryByTestId('aiExplainEntities')).not.toBeInTheDocument();
    expect(screen.queryByTestId('aiExplainTactics')).not.toBeInTheDocument();
    expect(screen.queryByTestId('aiExplainNextSteps')).not.toBeInTheDocument();
    // Summary still renders.
    expect(screen.getByTestId('aiExplainView')).toHaveTextContent(result.summary);
  });

  it('falls back to markdown when the model ignored the contract', () => {
    renderView({ result: undefined, rawResult: '# just markdown', hasRequested: true });
    expect(screen.getByTestId('aiExplainView')).toHaveTextContent('just markdown');
  });
});

import { useCallback, useEffect, useMemo, useState } from 'react';
import type { Replacements } from '@kbn/elastic-assistant-common';
import { replaceAnonymizedValuesWithOriginalValues } from '@kbn/elastic-assistant-common';
import {
  getCombinedMessage,
  getNewSelectedPromptContext,
  type PromptContext,
  useChatComplete,
  useFetchAnonymizationFields,
} from '@kbn/elastic-assistant';
import { i18n } from '@kbn/i18n';
import { useFetchDocumentSummary } from './use_fetch_document_summary';
import { useBulkUpdateDocumentSummary } from './use_bulk_update_document_summary';

const NO_SUMMARY_AVAILABLE = i18n.translate(
  'xpack.securitySolution.alertSummary.noSummaryAvailable',
  {
    defaultMessage: 'No summary available',
  }
);
const INVALID_RESPONSE = i18n.translate('xpack.securitySolution.alertSummary.invalidResponse', {
  defaultMessage:
    'Due to an unexpected issue, the AI model returned an invalid response. Please try again.',
});

export interface UseDocumentSummaryParams {
  /**
   * Id of the document we want to generate the summary for
   */
  documentId: string;
  /**
   * Value of securitySolution:defaultAIConnector
   */
  defaultConnectorId: string;
  /**
   * The context for the prompt
   */
  promptContext: PromptContext;
  /**
   * If true we'll show anonymized values
   */
  showAnonymizedValues?: boolean;
}

export interface UseDocumentSummaryResult {
  /**
   * Generated summary for the document
   */
  summary: string;
  /**
   * Timestamp (epoch ms) the persisted alert summary was last updated, or
   * `null` if no summary has been generated yet (or the API didn't return
   * an `updatedAt`). Used by the result footer to render
   * "Generated by AI on …".
   */
  generatedAt: number | null;
  /**
   * Returns true if the document has a summary
   */
  hasSummary: boolean;
  /**
   * Callback that fetches the AI summary
   */
  fetchAISummary: () => void;
  /**
   * Error message from the last failed generation attempt, or null if no error.
   */
  fetchError: string | null;
  /**
   * Returns true if no connector has been setup
   */
  isConnectorMissing: boolean;
  /**
   * Returns true while the fetch call is happening
   */
  isLoading: boolean;
  /**
   * Potenial user or prompt message replacements
   */
  messageAndReplacements: { message: string; replacements: Replacements } | null;
  /**
   * Recommended actions return when fetching the alert summary
   */
  recommendedActions: string | undefined;
}

/**
 * Attempts to parse a JSON object from an LLM response string using progressively
 * more lenient strategies:
 * 1. Direct JSON.parse (strict, as instructed by the prompt).
 * 2. Strip markdown code fences and retry (model ignored the no-fence instruction).
 * 3. Extract the first complete {...} block from the response (model added prose around it).
 * Returns null when no valid JSON object can be recovered.
 */
const extractJsonFromLlmResponse = (raw: string): Record<string, unknown> | null => {
  const stripped = raw
    .replace(/^```(?:json)?\s*/i, '')
    .replace(/\s*```\s*$/, '')
    .trim();
  const jsonBlock = raw.match(/\{[\s\S]*\}/)?.[0] ?? '';
  const candidates = [raw, stripped, jsonBlock];

  for (const candidate of candidates) {
    if (candidate) {
      try {
        const parsed: unknown = JSON.parse(candidate);
        if (parsed !== null && typeof parsed === 'object' && !Array.isArray(parsed)) {
          return parsed as Record<string, unknown>;
        }
      } catch {
        // try the next candidate
      }
    }
  }

  return null;
};

/**
 * Hook that generates the document AI summary along side other related items
 */
export const useDocumentSummary = ({
  documentId,
  defaultConnectorId,
  promptContext,
  showAnonymizedValues = false,
}: UseDocumentSummaryParams): UseDocumentSummaryResult => {
  const { abortStream, sendMessage } = useChatComplete({
    connectorId: defaultConnectorId,
  });

  const { data: anonymizationFields, isFetched: isFetchedAnonymizationFields } =
    useFetchAnonymizationFields();

  const [isConnectorMissing, setIsConnectorMissing] = useState<boolean>(false);
  const [fetchError, setFetchError] = useState<string | null>(null);
  const [summary, setSummary] = useState<string>(NO_SUMMARY_AVAILABLE);
  const [recommendedActions, setRecommendedActions] = useState<string | undefined>();
  const [messageAndReplacements, setMessageAndReplacements] = useState<{
    message: string;
    replacements: Replacements;
  } | null>(null);
  // indicates that a document summary exists or is being created/fetched
  const [hasSummary, setHasSummary] = useState<boolean>(false);
  const {
    data: fetchedSummary,
    refetch: refetchSummary,
    isFetched: isSummaryFetched,
  } = useFetchDocumentSummary({
    documentId,
    connectorId: defaultConnectorId,
  });
  const { bulkUpdate } = useBulkUpdateDocumentSummary();

  useEffect(() => {
    if (fetchedSummary.data.length > 0) {
      setHasSummary(true);
      setSummary(
        showAnonymizedValues
          ? fetchedSummary.data[0].summary
          : replaceAnonymizedValuesWithOriginalValues({
              messageContent: fetchedSummary.data[0].summary,
              replacements: fetchedSummary.data[0].replacements,
            })
      );
      setRecommendedActions(
        fetchedSummary.data[0].recommendedActions
          ? showAnonymizedValues
            ? fetchedSummary.data[0].recommendedActions
            : replaceAnonymizedValuesWithOriginalValues({
                messageContent: fetchedSummary.data[0].recommendedActions,
                replacements: fetchedSummary.data[0].replacements,
              })
          : undefined
      );
    } else {
      setHasSummary(false);
      setSummary(NO_SUMMARY_AVAILABLE);
      setRecommendedActions(undefined);
    }
  }, [fetchedSummary, showAnonymizedValues]);

  useEffect(() => {
    const fetchContext = async () => {
      const newSelectedPromptContext = await getNewSelectedPromptContext({
        anonymizationFields,
        promptContext,
      });
      const selectedPromptContexts = {
        [promptContext.id]: newSelectedPromptContext,
      };

      const userMessage = getCombinedMessage({
        currentReplacements: {},
        promptText: fetchedSummary.prompt,
        selectedPromptContexts,
      });
      const baseReplacements: Replacements = userMessage.replacements ?? {};

      const selectedPromptContextsReplacements = Object.values(
        selectedPromptContexts
      ).reduce<Replacements>((acc, context) => ({ ...acc, ...context.replacements }), {});

      const replacements: Replacements = {
        ...baseReplacements,
        ...selectedPromptContextsReplacements,
      };
      setMessageAndReplacements({ message: userMessage.content ?? '', replacements });
    };

    if (isFetchedAnonymizationFields && isSummaryFetched) {
      void fetchContext();
    }
  }, [
    anonymizationFields,
    isFetchedAnonymizationFields,
    isSummaryFetched,
    fetchedSummary.prompt,
    promptContext,
  ]);
  const [isGenerating, setIsGenerating] = useState(false);

  const fetchAISummary = useCallback(() => {
    const generateSummary = async (content: { message: string; replacements: Replacements }) => {
      setIsConnectorMissing(false);
      setFetchError(null);
      setIsGenerating(true);
      setHasSummary(true);

      const rawResponse = await sendMessage({
        ...content,
        promptIds: { promptGroupId: 'ease', promptId: 'alertSummarySystemPrompt' },
        query: {
          content_references_disabled: true,
        },
      });

      let responseSummary: string | undefined;
      let responseRecommendedActions: string | undefined;
      let hasInvalidResponse = false;

      const parsedResponse = extractJsonFromLlmResponse(rawResponse.response);
      if (parsedResponse != null) {
        if (
          typeof parsedResponse.summary === 'string' &&
          parsedResponse.summary.trim().length > 0
        ) {
          responseSummary = parsedResponse.summary;
          if (typeof parsedResponse.recommendedActions === 'string') {
            responseRecommendedActions = parsedResponse.recommendedActions;
          }
        } else {
          hasInvalidResponse = true;
        }
      } else {
        const trimmed = rawResponse.response?.trim() ?? '';
        if (trimmed.length > 0) {
          responseSummary = trimmed;
        } else {
          hasInvalidResponse = true;
        }
      }

      if (!rawResponse.isError && !hasInvalidResponse && responseSummary != null) {
        if (fetchedSummary.data.length > 0) {
          await bulkUpdate({
            documentSummary: {
              update: [
                {
                  id: fetchedSummary.data[0].id,
                  summary: responseSummary,
                  ...(responseRecommendedActions
                    ? { recommendedActions: responseRecommendedActions }
                    : {}),
                  replacements: content.replacements,
                },
              ],
            },
          });
        } else {
          await bulkUpdate({
            documentSummary: {
              create: [
                {
                  alertId: documentId,
                  summary: responseSummary,
                  ...(responseRecommendedActions
                    ? { recommendedActions: responseRecommendedActions }
                    : {}),
                  replacements: content.replacements,
                },
              ],
            },
          });
        }
        await refetchSummary();
      } else {
        const errorResponse = rawResponse.response ?? '';
        if (errorResponse.includes('Failed to load action')) {
          setIsConnectorMissing(true);
        } else {
          setFetchError(
            hasInvalidResponse && !rawResponse.isError ? INVALID_RESPONSE : errorResponse
          );
          if (fetchedSummary.data.length === 0) {
            setHasSummary(false);
          }
        }
      }
      setIsGenerating(false);
    };

    if (messageAndReplacements !== null) generateSummary(messageAndReplacements);
  }, [
    bulkUpdate,
    documentId,
    fetchedSummary.data,
    messageAndReplacements,
    refetchSummary,
    sendMessage,
  ]);

  useEffect(() => {
    return () => {
      abortStream();
    };
  }, [abortStream]);

  const generatedAt = useMemo<number | null>(() => {
    const updatedAt = fetchedSummary.data[0]?.updatedAt;
    if (!updatedAt) return null;
    const parsed = new Date(updatedAt).getTime();
    return Number.isNaN(parsed) ? null : parsed;
  }, [fetchedSummary.data]);

  return {
    summary,
    generatedAt,
    hasSummary,
    fetchAISummary,
    fetchError,
    isConnectorMissing,
    isLoading: isGenerating,
    messageAndReplacements,
    recommendedActions,
  };
};

import React, { memo, useMemo } from 'react';
import {
  EuiBadge,
  EuiButtonIcon,
  EuiCopy,
  EuiFlexGroup,
  EuiFlexItem,
  EuiHorizontalRule,
  EuiIcon,
  EuiPanel,
  EuiSpacer,
  EuiText,
  EuiTitle,
  EuiToolTip,
} from '@elastic/eui';
import { ExpandableSection } from '../../shared/components/expandable_section';
import type { EntityRiskLevel } from '../report_data';
import {
  AFFECTED_ENTITIES,
  AI_SUMMARY_GENERATED_AT,
  AI_SUMMARY_HIGHLIGHTS,
  AI_SUMMARY_RECOMMENDED_ACTIONS,
} from '../report_data';
import * as i18n from '../translations';

export const DETONATION_AI_SUMMARY_TEST_ID = 'detonationAiSummary';

const RISK_COLOR: Record<EntityRiskLevel, string> = {
  Critical: 'danger',
  High: 'warning',
  Medium: 'default',
};

/**
 * Plain-language AI summary of the detonation, laid out like the AI summary in the entity flyout:
 * titled highlights, the entities involved, recommended actions, and a "generated by" footer.
 */
export const AiSummary = memo(() => {
  const textToCopy = useMemo(
    () =>
      [
        ...AI_SUMMARY_HIGHLIGHTS.map(({ title, text }) => `${title}\n${text}`),
        `${i18n.RECOMMENDED_ACTIONS}\n${AI_SUMMARY_RECOMMENDED_ACTIONS.map((a) => `- ${a}`).join(
          '\n'
        )}`,
      ].join('\n\n'),
    []
  );

  return (
    <ExpandableSection
      data-test-subj={DETONATION_AI_SUMMARY_TEST_ID}
      expanded
      gutterSize="none"
      sectionId="detonationAiSummary"
      title={
        <>
          {i18n.AI_SUMMARY} <EuiIcon type="sparkles" aria-hidden={true} />
        </>
      }
    >
      <EuiPanel hasBorder hasShadow={false} paddingSize="m">
        {AI_SUMMARY_HIGHLIGHTS.map(({ title, text }, index) => (
          <React.Fragment key={title}>
            <EuiText size="xs" color="default">
              <strong>{title}</strong>
            </EuiText>
            <EuiSpacer size="xs" />
            <EuiText size="xs" color="default">
              {text}
            </EuiText>
            {index < AI_SUMMARY_HIGHLIGHTS.length - 1 && <EuiSpacer size="m" />}
          </React.Fragment>
        ))}

        <EuiSpacer size="m" />
        <EuiText size="xs" color="default">
          <strong>{i18n.AFFECTED_ENTITIES}</strong>
        </EuiText>
        <EuiSpacer size="xs" />
        {AFFECTED_ENTITIES.map((entity) => (
          <EuiFlexGroup
            key={entity.id}
            gutterSize="s"
            alignItems="center"
            responsive={false}
            css={{ padding: '4px 0' }}
            data-test-subj={`detonationAffectedEntity-${entity.name}`}
          >
            <EuiFlexItem grow={false}>
              <EuiIcon type={entity.type === 'host' ? 'storage' : 'user'} aria-hidden={true} />
            </EuiFlexItem>
            <EuiFlexItem>
              <EuiText size="xs">
                <strong>{entity.name}</strong>
              </EuiText>
              <EuiText size="xs" color="subdued">
                {entity.note}
              </EuiText>
            </EuiFlexItem>
            <EuiFlexItem grow={false}>
              <EuiBadge color={RISK_COLOR[entity.risk]}>
                {i18n.RISK_LABEL(entity.risk, entity.riskScore)}
              </EuiBadge>
            </EuiFlexItem>
          </EuiFlexGroup>
        ))}

        <EuiHorizontalRule margin="m" />
        <EuiFlexGroup alignItems="center" gutterSize="xs" responsive={false}>
          <EuiFlexItem grow={false}>
            <EuiIcon type="documentation" size="m" aria-hidden={true} />
          </EuiFlexItem>
          <EuiFlexItem grow={false}>
            <EuiTitle size="xxs">
              <h4>{i18n.RECOMMENDED_ACTIONS}</h4>
            </EuiTitle>
          </EuiFlexItem>
        </EuiFlexGroup>
        <EuiSpacer size="s" />
        <EuiText size="xs" color="default">
          <ul>
            {AI_SUMMARY_RECOMMENDED_ACTIONS.map((action) => (
              <li key={action}>{action}</li>
            ))}
          </ul>
        </EuiText>

        <EuiHorizontalRule margin="m" />
        <EuiFlexGroup alignItems="center" justifyContent="spaceBetween" responsive={false}>
          <EuiFlexItem grow={false}>
            <EuiText size="xs" color="subdued">
              {i18n.GENERATED_BY_AI(AI_SUMMARY_GENERATED_AT)}
            </EuiText>
          </EuiFlexItem>
          <EuiFlexItem grow={false}>
            <EuiCopy textToCopy={textToCopy}>
              {(copy) => (
                <EuiToolTip content={i18n.COPY_SUMMARY} disableScreenReaderOutput>
                  <EuiButtonIcon
                    iconType="copy"
                    size="xs"
                    aria-label={i18n.COPY_SUMMARY}
                    onClick={copy}
                    data-test-subj="detonationAiSummaryCopy"
                  />
                </EuiToolTip>
              )}
            </EuiCopy>
          </EuiFlexItem>
        </EuiFlexGroup>
      </EuiPanel>
    </ExpandableSection>
  );
});

AiSummary.displayName = 'AiSummary';

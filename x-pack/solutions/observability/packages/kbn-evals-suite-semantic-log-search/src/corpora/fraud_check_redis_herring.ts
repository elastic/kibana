import type { EvalQuery } from '../ground_truth';
import type { CorpusProfile } from './types';

/**
 * Classes of message in the corpus, labelled by meaning rather than vocabulary.
 *
 * The scenario injects misleading Redis and Kafka lines alongside a real fraud-check gateway
 * timeout, so the question this corpus asks is whether a ranker separates the incident from
 * plausible-looking noise rather than whether it can retrieve at all.
 * src/platform/packages/shared/kbn-synthtrace/src/lib/service_graph_logs/log_catalog/
 */
const MESSAGE_CLASSES = {
  /**
   * Downstream timeout: the actual fraud-check incident.
   * Templates: `log_catalog/request.ts`, one label per runtime, which is why four unrelated
   * strings all mean the same failure.
   */
  gatewayTimeout: [
    'context deadline exceeded calling downstream',
    '"msg":"downstream timeout"',
    'Upstream timeout calling',
    'Downstream timeout calling',
  ],

  /**
   * Circuit breaker warnings: the error rate rising toward the trip threshold, emitted ahead of
   * the full gateway timeout in each cycle, which is what makes them gradeable as the earlier
   * and weaker signal.
   * Templates: `log_catalog/request.ts`.
   */
  circuitBreakerWarning: [
    'circuit breaker: error rate approaching threshold',
    'circuit breaker threshold approaching',
  ],

  /**
   * Redis and Kafka noise, injected by the scenario's `ghostMentions` rather than generated from
   * a catalog template, which is why these two labels are stable across runtimes and seeds.
   * A ranker that retrieves them for a gateway-timeout question is following surface keywords.
   * https://github.com/elastic/kibana/blob/0021bfbb5887/src/platform/packages/shared/kbn-synthtrace/src/scenarios/sigevents/mock_apps/claims.ts#L121
   */
  ghostNoise: [
    'Redis connection timeout after 5000ms',
    'Kafka consumer lag detected on topic claim-events',
  ],
} as const;

const QUERIES: readonly EvalQuery[] = [
  {
    id: 'fraud_check_timed_out',
    kind: 'semantic',
    question: 'fraud check service timing out',
    graded: [
      { grade: 2, matches: MESSAGE_CLASSES.gatewayTimeout },
      { grade: 1, matches: MESSAGE_CLASSES.circuitBreakerWarning },
    ],
    traps: MESSAGE_CLASSES.ghostNoise,
    note: 'Ghost mentions look like infrastructure failures (Redis timeout, Kafka lag) but are noise unrelated to the actual incident.',
  },

  {
    id: 'upstream_deadline_exceeded',
    kind: 'semantic',
    question: 'upstream requests exceeding their deadline',
    graded: [
      { grade: 2, matches: MESSAGE_CLASSES.gatewayTimeout },
      { grade: 1, matches: MESSAGE_CLASSES.circuitBreakerWarning },
    ],
    traps: MESSAGE_CLASSES.ghostNoise,
    note: 'Paraphrase of fraud_check_timed_out with no vocabulary overlap with the log lines. Tests vocabulary-independent ranking across both query phrasing dimensions.',
  },

  {
    id: 'circuit_breaker_approaching_threshold',
    kind: 'semantic',
    question: 'circuit breaker approaching error rate threshold',
    graded: [
      { grade: 2, matches: MESSAGE_CLASSES.circuitBreakerWarning },
      { grade: 1, matches: MESSAGE_CLASSES.gatewayTimeout },
    ],
    traps: MESSAGE_CLASSES.ghostNoise,
    note: 'Warnings are grade 2 here; full timeouts are grade 1 (exceeded threshold, not approaching it). Tests whether the ranker prefers early-warning signals for early-warning questions.',
  },
];

/**
 * Corpus generated by the synthtrace `sigevents` scenario `fraud_check_redis_herring`.
 *
 * Gateway timeouts are injected into the fraud-check service at a 70% rate for 5 minutes of each
 * 10-minute cycle, with the Redis and Kafka ghost mentions firing throughout rather than only
 * during the failure, so the noise is present even in the windows that contain no incident.
 * Its label set is disjoint from `sigevents_postgres_timeout`, which is what makes it usable as
 * an overfitting guard: a change tuned against one corpus is scored here on different strings in
 * a different domain.
 */
export const sigeventsFraudCheckRedisHerring: CorpusProfile = {
  id: 'sigevents_fraud_check_redis_herring',
  description:
    'Gateway timeout signals mixed with Redis and Kafka ghost mentions from the fraud_check_redis_herring scenario',

  target: 'logs-synth-default',
  timeRange: { start: 'now-2h', end: 'now' },

  setupCommand: `node scripts/synthtrace sigevents \\
  --target=http://elastic:changeme@localhost:9220 \\
  --kibana=http://elastic:changeme@localhost:5620 \\
  --scenarioOpts="scenario=fraud_check_redis_herring,seed=42" \\
  --from=now-2h --to=now --clean`,

  messageClasses: MESSAGE_CLASSES,
  queries: QUERIES,

  k: 10,
  relevanceThreshold: 2,
  maxPatterns: 20,
};

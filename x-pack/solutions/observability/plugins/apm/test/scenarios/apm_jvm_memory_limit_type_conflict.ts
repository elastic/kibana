/**
 * Reproduces the `verification_exception` on the Java dashboards when
 * `jvm.memory.limit` is mapped as `long` in some backing indices and as `double` in others
 * (https://github.com/elastic/kibana/issues/304044, fix: https://github.com/elastic/kibana/pull/305126):
 *
 *   Cannot use field [jvm.memory.limit] due to ambiguities being mapped as [2] incompatible types:
 *   [double] in [<backing indices of ...>] and [long] in [<other backing indices>]
 *
 * The two ingestion paths are generated by separate runs (`path` option) so a service never mixes
 * classic APM and OTel documents, which would show the "overlapping data from multiple
 * instrumentation types" callout on the Metrics tab:
 *
 * - path=otel (default service `jvm-memory-limit-otel`): OTel pipeline, EDOT-like Java service.
 *   Traces and rollups go to *.otel-* streams, as do the metrics in
 *   metrics-jvm_limit_{long,double}.otel-default. Needs `*.otel-*` in the deployment's APM index
 *   settings. Uses the otel_native Java dashboard (fixed by the PR).
 * - path=apm (default service `jvm-memory-limit-apm`): classic APM pipeline only, with no OTel fields
 *   (no telemetry.sdk.*, resource.attributes.*, scope.*). Traces and rollups go to traces-apm* and
 *   metrics-apm*, and the metrics in metrics-apm.jvm_limit_{long,double}-default. Uses the classic
 *   opentelemetry_java dashboard, which also reads `jvm.memory.limit` and is not covered by the PR.
 *
 * Within each path `jvm.memory.limit` is mapped as `long` in one data stream and `double` in the other.
 * The documents mirror real `generic.otel` Java metrics, one service instance per variant.
 *
 * Run (each run only removes its own metrics data streams, `--clean` removes the standard APM data
 * streams, so pass it on the first run only):
 *   node scripts/synthtrace apm_jvm_memory_limit_type_conflict --clean --scenarioOpts.path=apm
 *   node scripts/synthtrace apm_jvm_memory_limit_type_conflict --scenarioOpts.path=otel
 *
 * Scenario options:
 * - path ("apm" | "otel", default: "apm"): ingestion path to generate
 * - serviceName (string, default: "jvm-memory-limit-<path>"): service name
 * - rpm (number, default: 2): transactions per minute
 */

import type { ApmFields, ApmOtelFields } from '@kbn/synthtrace-client';
import { apm, ApmSynthtracePipelineSchema } from '@kbn/synthtrace-client';
import type { Client } from '@elastic/elasticsearch';
import type { IndicesPutIndexTemplateRequest } from '@elastic/elasticsearch/lib/api/types';
import type { Scenario } from '@kbn/synthtrace';
import { withClient } from '@kbn/synthtrace';
import { getSynthtraceEnvironment } from '@kbn/synthtrace';

const ENVIRONMENT = getSynthtraceEnvironment(__filename);

type IngestionPath = 'apm' | 'otel';

const DEFAULT_SCENARIO_OPTS = {
  path: 'apm' as IngestionPath,
  serviceName: undefined as string | undefined,
  rpm: 2,
};

function assertNoUnknownScenarioOpts(opts: Record<string, unknown>) {
  const unknown = Object.keys(opts).filter((k) => !(k in DEFAULT_SCENARIO_OPTS));
  if (unknown.length) {
    throw new Error(`Unknown scenarioOpts: ${unknown.join(', ')}`);
  }
}

interface LimitStream {
  /** data stream is `metrics-${dataset}-default` */
  dataset: string;
  limitType: 'long' | 'double';
  instanceId: string;
  containerId: string;
  hostName: string;
  memoryPool: string;
  memoryLimit: number;
}

const VARIANTS = [
  {
    variant: 'long',
    limitType: 'long',
    instanceId: 'f502893b-c400-40c0-8cd0-3391c8f538a3',
    containerId: '520eff5bf97049f6059b87657e467ff402a0571b60691e56e1de8b1a6d5deeef',
    hostName: 'sylvain-elastic',
    memoryPool: "CodeHeap 'non-profiled nmethods'",
    memoryLimit: 122_028_032,
  },
  {
    variant: 'double',
    limitType: 'double',
    instanceId: '39ecdf5d-0f7c-4688-aebd-615b2c83619b',
    containerId: '7090b55d7c176a092f599b4727b01c914a6db317d7b13728db117252d4349c8b',
    hostName: '7090b55d7c17',
    memoryPool: "CodeHeap 'non-nmethods'",
    memoryLimit: 7_606_272,
  },
] as const;

// `.otel` datasets are matched by `metrics-*.otel-*`, `apm.` ones by `metrics-apm*`
const getStreams = (path: IngestionPath): LimitStream[] =>
  VARIANTS.map((v) => ({
    ...v,
    dataset: path === 'otel' ? `jvm_limit_${v.variant}.otel` : `apm.jvm_limit_${v.variant}`,
  }));

const indexName = ({ dataset }: LimitStream) => `metrics-${dataset}-default`;
const templateName = ({ dataset }: LimitStream) => `metrics-${dataset}`;

interface Doc {
  index: string;
  doc: Record<string, unknown>;
}

function generateStreamDocs(
  path: IngestionPath,
  stream: LimitStream,
  serviceName: string,
  startMs: number,
  endMs: number
): Doc[] {
  const docs: Doc[] = [];
  const intervalMs = 60_000;

  // Fields shared by both paths: what a classic APM metric document carries
  const base = {
    'data_stream.type': 'metrics',
    'data_stream.dataset': stream.dataset,
    'data_stream.namespace': 'default',
    'service.name': serviceName,
    'service.environment': ENVIRONMENT,
    'service.node.name': stream.instanceId,
    'service.instance.id': stream.instanceId,
    'host.name': stream.hostName,
    'container.id': stream.containerId,
    'agent.name': 'opentelemetry/java/elastic',
  };

  // OTel-only fields: the flat resource/scope attributes of a `generic.otel` metric document
  const otelFields = () => {
    const resource = {
      'container.id': stream.containerId,
      'deployment.environment.name': ENVIRONMENT,
      'host.arch': 'amd64',
      'host.name': stream.hostName,
      'os.type': 'linux',
      'process.pid': 1,
      'process.runtime.name': 'OpenJDK Runtime Environment',
      'process.runtime.version': '17.0.18+8-Debian-1deb12u1',
      'service.criticality': 'low',
      'service.instance.id': stream.instanceId,
      'service.name': serviceName,
      'telemetry.sdk.language': 'java',
      'telemetry.sdk.name': 'opentelemetry',
    };

    return {
      ...resource,
      ...Object.fromEntries(
        Object.entries(resource).map(([key, value]) => [`resource.attributes.${key}`, value])
      ),
      'event.dataset': stream.dataset,
      'service.language.name': 'java',
      'scope.name': 'io.opentelemetry.runtime-telemetry-java8',
      'telemetry.distro.name': 'elastic',
    };
  };

  // Classic APM metric documents are identified by processor.event / metricset.name
  const classicFields = { 'processor.event': 'metric', 'metricset.name': 'app' };

  // Classic APM carries OTel attributes as labels, which the classic opentelemetry_java dashboard reads
  const classicLabels = (type: string, pool: string) => ({
    'labels.jvm_memory_type': type,
    'labels.jvm_memory_pool_name': pool,
  });

  const pathFields = path === 'otel' ? otelFields() : classicFields;

  for (let ts = startMs; ts <= endMs; ts += intervalMs) {
    const timestamp = new Date(ts).toISOString();

    docs.push({
      index: indexName(stream),
      doc: {
        ...base,
        ...pathFields,
        '@timestamp': timestamp,
        ...(path === 'otel'
          ? {
              start_timestamp: new Date(startMs).toISOString(),
              'attributes.jvm.memory.pool.name': stream.memoryPool,
              'attributes.jvm.memory.type': 'non_heap',
              'metrics.jvm.memory.limit': stream.memoryLimit,
              unit: 'By',
            }
          : {}),
        'jvm.memory.pool.name': stream.memoryPool,
        'jvm.memory.type': 'non_heap',
        'jvm.memory.limit': stream.memoryLimit,
        'jvm.memory.committed': stream.memoryLimit,
        ...(path === 'apm' ? classicLabels('non_heap', stream.memoryPool) : {}),
      },
    });

    // Companion metrics so the dashboard has used/committed/limit side by side
    docs.push({
      index: indexName(stream),
      doc: {
        ...base,
        ...pathFields,
        '@timestamp': timestamp,
        'jvm.memory.type': 'heap',
        'jvm.memory.pool.name': 'G1 Old Gen',
        ...(path === 'apm' ? classicLabels('heap', 'G1 Old Gen') : {}),
        'jvm.memory.used': 400_000_000 + Math.floor(Math.random() * 100_000_000),
        'jvm.memory.committed': 500_000_000 + Math.floor(Math.random() * 50_000_000),
        'jvm.memory.used_after_last_gc': 150_000_000 + Math.floor(Math.random() * 40_000_000),
        'jvm.memory.limit': 1_073_741_824,
        'jvm.cpu.recent_utilization': 0.3 + Math.random() * 0.2,
        'jvm.system.cpu.utilization': 0.4 + Math.random() * 0.2,
        'jvm.thread.count': 35 + Math.floor(Math.random() * 10),
        'jvm.class.count': 7500 + Math.floor(Math.random() * 500),
        'jvm.thread.daemon': true,
        'jvm.thread.state': 'runnable',
      },
    });
  }

  return docs;
}

async function ensureTemplate(esClient: Client, stream: LimitStream) {
  await esClient.indices.putIndexTemplate({
    name: templateName(stream),
    index_patterns: [`metrics-${stream.dataset}-*`],
    data_stream: {},
    priority: 500,
    template: {
      mappings: {
        // Strings as keyword, like the managed APM templates, so e.g. host.name does not conflict
        dynamic_templates: [
          { strings_as_keyword: { match_mapping_type: 'string', mapping: { type: 'keyword' } } },
        ],
        properties: {
          '@timestamp': { type: 'date' },
          'service.name': { type: 'keyword' },
          'service.node.name': { type: 'keyword' },
          'jvm.memory.type': { type: 'keyword' },
          'jvm.memory.pool.name': { type: 'keyword' },
          // The conflicting field: long in one data stream, double in the other
          'jvm.memory.limit': { type: stream.limitType },
          'metrics.jvm.memory.limit': { type: stream.limitType },
          'jvm.memory.used': { type: 'long' },
          'jvm.memory.committed': { type: 'long' },
          'jvm.memory.used_after_last_gc': { type: 'long' },
          'jvm.thread.daemon': { type: 'boolean' },
          'jvm.thread.state': { type: 'keyword' },
          'jvm.cpu.recent_utilization': { type: 'double' },
          'jvm.system.cpu.utilization': { type: 'double' },
          // double, like the classic APM metrics in other clusters, so only jvm.memory.limit conflicts
          'jvm.thread.count': { type: 'double' },
          'jvm.class.count': { type: 'long' },
        },
      },
    },
  } as unknown as IndicesPutIndexTemplateRequest);
}

async function cleanup(esClient: Client, streams: LimitStream[]) {
  for (const stream of streams) {
    await esClient.indices.deleteDataStream({ name: indexName(stream) }).catch(() => {});
    await esClient.indices.deleteIndexTemplate({ name: templateName(stream) }).catch(() => {});
  }
}

async function bulkIndexDocs(esClient: Client, docs: Doc[]) {
  const batchSize = 2000;
  for (let i = 0; i < docs.length; i += batchSize) {
    const batch = docs.slice(i, i + batchSize);
    const body = batch.flatMap(({ index, doc }) => [{ create: { _index: index } }, doc]);
    const response = await esClient.bulk({ body, refresh: false });
    if (response.errors) {
      throw new Error(`Bulk indexing into ${batch[0].index} reported errors`);
    }
  }
}

const scenario: Scenario<ApmFields | ApmOtelFields> = async ({
  from,
  to,
  logger,
  ...runOptions
}) => {
  const scenarioOpts = (runOptions.scenarioOpts ?? {}) as Record<string, unknown>;
  assertNoUnknownScenarioOpts(scenarioOpts);
  const opts = { ...DEFAULT_SCENARIO_OPTS, ...scenarioOpts };
  const { path, rpm } = opts;
  if (path !== 'apm' && path !== 'otel') {
    throw new Error(`Unknown path "${path}", expected "apm" or "otel"`);
  }
  const serviceName = opts.serviceName ?? `jvm-memory-limit-${path}`;
  const streams = getStreams(path);

  return {
    bootstrap: async (_synthtraceClients, _kibanaClient, esClient) => {
      // Re-running must recreate the data streams, otherwise an existing mapping would win
      await cleanup(esClient, streams);

      for (const stream of streams) {
        logger.info(`Creating ${stream.limitType} template for ${indexName(stream)}...`);
        await ensureTemplate(esClient, stream);

        const docs = generateStreamDocs(path, stream, serviceName, from, to);
        await bulkIndexDocs(esClient, docs);
        logger.info(`Indexed ${docs.length} docs into ${indexName(stream)}`);
      }

      await esClient.indices.refresh({ index: streams.map(indexName).join(',') });
    },

    generate: ({ range, clients: { apmEsClient } }) => {
      if (path === 'otel') {
        const otelInstance = apm
          .otelService({
            name: serviceName,
            namespace: ENVIRONMENT,
            sdkLanguage: 'java',
            sdkName: 'opentelemetry',
            distro: 'elastic',
          })
          .instance(`${serviceName}-instance`);

        return withClient(
          apmEsClient,
          range.ratePerMinute(rpm).generator((timestamp) =>
            otelInstance
              .span({ name: 'POST /api/fraud-check', kind: 'Server' })
              .timestamp(timestamp)
              .duration(200)
              .success()
              .children(
                otelInstance
                  .span({ name: 'SELECT * FROM transactions', kind: 'Internal' })
                  .timestamp(timestamp)
                  .duration(100)
                  .success()
              )
          )
        );
      }

      const instance = apm
        .service({
          name: serviceName,
          environment: ENVIRONMENT,
          agentName: 'opentelemetry/java/elastic',
        })
        .instance(`${serviceName}-instance`);

      return withClient(
        apmEsClient,
        range
          .ratePerMinute(rpm)
          .generator((timestamp) =>
            instance
              .transaction({ transactionName: 'POST /api/fraud-check' })
              .timestamp(timestamp)
              .duration(200)
              .success()
          )
      );
    },

    setupPipeline: ({ apmEsClient }) => {
      if (path === 'otel') {
        apmEsClient.setPipeline(apmEsClient.resolvePipelineType(ApmSynthtracePipelineSchema.Otel));
      }
    },

    // No teardown - data must persist for Kibana UI validation.
  };
};

export default scenario;

import { z, lazySchema } from '@kbn/zod';

export const TLSParamsType = lazySchema(() =>
  z.looseObject({
    search: z.string().optional(),
    certAgeThreshold: z.number().optional(),
    certExpirationThreshold: z.number().optional(),
  })
);

export const StatusCheckFiltersType = lazySchema(() =>
  z.looseObject({
    'monitor.type': z.array(z.string()),
    'observer.geo.name': z.array(z.string()),
    tags: z.array(z.string()),
    'url.port': z.array(z.string()),
  })
);

export const AtomicStatusCheckParamsType = lazySchema(() =>
  z.looseObject({
    numTimes: z.number(),
    timerangeCount: z.number(),
    timerangeUnit: z.string(),
    search: z.string().optional(),
    filters: StatusCheckFiltersType.optional(),
    shouldCheckStatus: z.boolean().optional(),
    isAutoGenerated: z.boolean().optional(),
    shouldCheckAvailability: z.boolean().optional(),
  })
);

export const StatusCheckParamsType = lazySchema(() =>
  z.looseObject({
    filters: z.string().optional(),
    shouldCheckStatus: z.boolean().optional(),
    isAutoGenerated: z.boolean().optional(),
    locations: z.array(z.string()),
    numTimes: z.number(),
    timerange: z.looseObject({
      from: z.string(),
      to: z.string(),
    }),
  })
);

export const RangeUnitType = lazySchema(() => z.enum(['s', 'm', 'h', 'd', 'w', 'M', 'y']));

export const GetMonitorAvailabilityParamsType = lazySchema(() =>
  z.looseObject({
    range: z.number(),
    rangeUnit: RangeUnitType,
    threshold: z.string(),
    filters: z.string().optional(),
  })
);

export const MonitorAvailabilityType = lazySchema(() =>
  z.looseObject({
    availability: GetMonitorAvailabilityParamsType,
    shouldCheckAvailability: z.boolean(),
    filters: StatusCheckFiltersType.optional(),
    search: z.string().optional(),
  })
);

import type { GithubIssueEvent } from '../failed_tests_reporter/github_api';
import { githubIssue } from '../flaky_test_issues/test_fixtures';
import {
  FIX_LABEL,
  FIXABLE_LABEL,
  episodeStart,
  isFixAttempt,
  labeledFixableAfter,
  latestReopen,
  openPeriods,
} from './history';

const day = (n: number) => `2026-09-${String(n).padStart(2, '0')}T12:00:00Z`;

const event = (id: number, type: string, overrides: Partial<GithubIssueEvent> = {}) => ({
  id,
  event: type,
  created_at: day(id),
  ...overrides,
});

describe('isFixAttempt', () => {
  it('counts the trigger label and comments the fixer posted', () => {
    expect(isFixAttempt(event(1, 'labeled', { label: { name: FIX_LABEL } }))).toBe(true);
    expect(
      isFixAttempt(
        event(2, 'commented', {
          user: { login: 'github-actions[bot]' },
          body: '<!-- gh-aw-agentic-workflow: Flaky Test Fixer, id: 1 -->',
        })
      )
    ).toBe(true);
  });

  it('ignores other labels and fixer markers posted by anyone else', () => {
    expect(isFixAttempt(event(1, 'labeled', { label: { name: FIXABLE_LABEL } }))).toBe(false);
    expect(
      isFixAttempt(
        event(2, 'commented', {
          user: { login: 'someone' },
          body: '> Generated by [Flaky Test Fixer](https://example.com)',
        })
      )
    ).toBe(false);
  });
});

describe('latestReopen and labeledFixableAfter', () => {
  it('finds the latest reopen and a fixable verdict after it', () => {
    const events = [
      event(3, 'reopened'),
      event(1, 'reopened'),
      event(4, 'labeled', { label: { name: FIXABLE_LABEL } }),
    ];
    expect(latestReopen(events)).toBe(events[0]);
    expect(labeledFixableAfter(events, events[0])).toBe(true);
    expect(labeledFixableAfter(events, event(5, 'reopened'))).toBe(false);
  });
});

describe('openPeriods', () => {
  it('follows closes and reopens', () => {
    const issue = githubIssue({ number: 1, created_at: day(1) });
    expect(openPeriods({ issue, events: [event(4, 'reopened'), event(2, 'closed')] })).toEqual([
      { from: day(1), to: day(2) },
      { from: day(4) },
    ]);
  });

  it('trusts the current state over a timeline that lags behind it', () => {
    const closed = githubIssue({
      number: 1,
      created_at: day(1),
      state: 'closed',
      closed_at: day(3),
    });
    expect(openPeriods({ issue: closed, events: [] })).toEqual([{ from: day(1), to: day(3) }]);
    const open = githubIssue({ number: 2, created_at: day(1) });
    expect(openPeriods({ issue: open, events: [event(2, 'closed')] })).toEqual([{ from: day(1) }]);
  });
});

describe('episodeStart', () => {
  it('is undefined when no issue is open', () => {
    expect(episodeStart([{ from: day(1), to: day(2) }])).toBeUndefined();
  });

  it('starts with the earliest period that is still open', () => {
    expect(episodeStart([{ from: day(5) }, { from: day(3) }])).toBe(day(3));
  });

  it('extends back through overlapping periods, but not across a gap', () => {
    const periods = [
      { from: day(1), to: day(2) },
      { from: day(3), to: day(6) },
      { from: day(5), to: day(8) },
      { from: day(7) },
    ];
    expect(episodeStart(periods)).toBe(day(3));
  });
});

import type { GithubIssue, GithubIssueEvent } from '../failed_tests_reporter/github_api';

/** Requests a fix: the Flaky Test Fixer runs when it is applied. */
export const FIX_LABEL = 'ai:fix-flaky';
/** The investigator's verdict that a repository change can fix the failure. */
export const FIXABLE_LABEL = 'failure:ai-fixable';

/** Accounts that post the Flaky Test Fixer's comments, and markers only its comments carry. */
const FIXER_AUTHORS = ['kibanamachine', 'github-actions[bot]'];
const FIXER_MARKERS = [
  '<!-- gh-aw-agentic-workflow: Flaky Test Fixer,',
  '> Generated by [Flaky Test Fixer](',
];

/** An issue with its timeline. */
export interface IssueHistory {
  issue: GithubIssue;
  events: GithubIssueEvent[];
}

/** A stretch of time an issue was open; `to` is absent while it still is. */
export interface OpenPeriod {
  from: string;
  to?: string;
}

const chronologically = (a: GithubIssueEvent, b: GithubIssueEvent): number =>
  a.created_at.localeCompare(b.created_at) || a.id - b.id;

export const latestReopen = (events: GithubIssueEvent[]): GithubIssueEvent | undefined =>
  events
    .filter((event) => event.event === 'reopened')
    .sort(chronologically)
    .at(-1);

/**
 * A fix request, or a fixer comment. Removing the trigger label leaves the `labeled` event, and
 * a comment also records a manual dispatch or an attempt that produced no PR.
 */
export const isFixAttempt = (event: GithubIssueEvent): boolean =>
  (event.event === 'labeled' && event.label?.name === FIX_LABEL) ||
  (FIXER_AUTHORS.includes(event.user?.login ?? '') &&
    FIXER_MARKERS.some((marker) => event.body?.includes(marker)));

/** `failure:ai-fixable` applied after the event, i.e. by an investigation since. */
export const labeledFixableAfter = (events: GithubIssueEvent[], after: GithubIssueEvent): boolean =>
  events.some(
    (event) =>
      event.event === 'labeled' &&
      event.label?.name === FIXABLE_LABEL &&
      event.created_at > after.created_at
  );

export const openPeriods = ({ issue, events }: IssueHistory): OpenPeriod[] => {
  const periods: OpenPeriod[] = [{ from: issue.created_at }];
  const transitions = events
    .filter(({ event }) => event === 'closed' || event === 'reopened')
    .sort(chronologically);
  for (const { event, created_at: at } of transitions) {
    const last = periods[periods.length - 1];
    if (event === 'closed' && last.to === undefined) last.to = at;
    if (event === 'reopened' && last.to !== undefined) periods.push({ from: at });
  }
  // The issue's current state wins over a timeline that lags behind it
  const last = periods[periods.length - 1];
  if (issue.state === 'open') {
    last.to = undefined;
  } else if (last.to === undefined) {
    last.to = issue.closed_at ?? undefined;
  }
  return periods;
};

/**
 * Start of the stretch, up to now, that the open periods cover without a gap: when the file's
 * current episode began. Undefined when none of them is still open.
 */
export const episodeStart = (periods: OpenPeriod[]): string | undefined => {
  let start = periods
    .filter(({ to }) => to === undefined)
    .map(({ from }) => from)
    .sort()[0];
  if (start === undefined) return undefined;
  for (let extended = true; extended; ) {
    extended = false;
    for (const { from, to } of periods) {
      if (to !== undefined && from < start && to >= start) {
        start = from;
        extended = true;
      }
    }
  }
  return start;
};

import type { ProfileFile } from './api';

// Revoking the URL right after the click can cancel the download in some browsers.
const REVOKE_URL_DELAY_MS = 30_000;

/** Saves a profile file through the browser's download mechanism. */
export function downloadFile({ fileName, blob }: ProfileFile): void {
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = fileName;
  document.body.appendChild(link);
  link.click();
  link.remove();
  window.setTimeout(() => URL.revokeObjectURL(url), REVOKE_URL_DELAY_MS);
}

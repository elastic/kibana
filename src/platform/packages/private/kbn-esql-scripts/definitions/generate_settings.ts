import { camelCase } from 'lodash';
import { join } from 'path';
import { settingDefinitions } from '@elastic/esql-definitions/settings';
import { clearDocumentationDirectives } from '../lib/docs';
import type { GeneratedFile } from '../lib/generated_file';
import { GENERATED_DEFINITIONS_DIR } from './constants';

// We exclude the time_zone setting as we decided that we won't support it in Kibana
const SETTINGS_TO_EXCLUDE = new Set(['time_zone']);

/** Renders the settings and `EsqlSettingNames` consumed by `@kbn/esql-language`. */
export const renderSettings = (): GeneratedFile[] => {
  const settingConstants = settingDefinitions
    .map((setting) => {
      const settingName = setting.name;
      const modifiedSetting = {
        ...setting,
        description: clearDocumentationDirectives(setting.description),
        ignoreAsSuggestion: setting.snapshotOnly || SETTINGS_TO_EXCLUDE.has(settingName),
      };
      return `const ${camelCase(settingName)} = ${JSON.stringify(modifiedSetting, null, 2).replace(
        `"name": "${settingName}"`,
        `name: EsqlSettingNames.${settingName.toUpperCase()}`
      )};`;
    })
    .join('\n\n');

  const settingNames = settingDefinitions.map((setting) => camelCase(setting.name)).join(', ');

  const settingEnum = `export enum EsqlSettingNames {
${settingDefinitions
  .map((setting) => `  ${setting.name.toUpperCase()} = '${setting.name}',`)
  .join('\n')}
}`;

  const tsContent = `
// Do not edit this manually... generated by scripts/generate_settings.ts
${settingEnum}

${settingConstants}

export const settings = [
  ${settingNames}
];
`;

  return [{ path: join(GENERATED_DEFINITIONS_DIR, 'settings.ts'), content: tsContent }];
};

/** A valid Terraform identifier from a display name, `fallback` when nothing in the name qualifies. */
export const toResourceName = (displayName: string, fallback: string): string => {
  const name = displayName
    .normalize('NFKD')
    .replace(/\p{M}/gu, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '');
  if (!name) return fallback;
  return /^[0-9]/.test(name) ? `_${name}` : name;
};

import Fsp from 'fs/promises';
import Path from 'path';

import { REPO_ROOT } from '../../lib/paths.mjs';

const WORKSPACE_PATH = Path.resolve(REPO_ROOT, 'pnpm-workspace.yaml');
const ROOT_PACKAGE_JSON_PATH = Path.resolve(REPO_ROOT, 'package.json');
const GITIGNORE_PATH = Path.resolve(REPO_ROOT, '.gitignore');
const GITIGNORE_START = '# START GENERATED PNPM PACKAGE JSONS';
const GITIGNORE_END = '# END GENERATED PNPM PACKAGE JSONS';

const HEADER = [
  '# This file is generated by `kbn_pm bootstrap`. Do not edit by hand.',
  '# Workspace membership is derived from kibana.jsonc discovery (package-map).',
  '# Install settings + overrides are mirrored from package.json "pnpm" (the',
  '# authored source of truth); pnpm 11 only reads them from here.',
].join('\n');

// pnpm behavioral settings. pnpm 11 no longer reads these from .npmrc, so they
// live here. Emulates Kibana's flat, phantom-hoisted node_modules (parity with
// the old yarn-classic single node_modules layout).
const INSTALL_SETTINGS = [
  'nodeLinker: hoisted',
  "hoistPattern:\n  - '*'",
  "publicHoistPattern:\n  - '*'",
  'shamefullyHoist: true',
  'autoInstallPeers: true',
  'strictPeerDependencies: false',
  'dedupePeerDependents: true',
].join('\n');

/**
 * Writes pnpm-workspace.yaml and synthesizes a minimal package.json for any
 * package that doesn't ship one. Kibana packages are identified by kibana.jsonc,
 * but pnpm workspaces need a package.json with a matching `name` per package, so
 * we generate the missing ones (gitignored) from the manifest id + root version.
 *
 * @param {import('@kbn/repo-packages').Package[]} pkgs
 * @param {string} rootVersion
 * @param {import('src/platform/packages/private/kbn-some-dev-log').SomeDevLog} log
 */
export async function regeneratePnpmWorkspace(pkgs, rootVersion, log) {
  await writeWorkspaceFile(pkgs, log);
  const generatedRepoRels = await synthesizeMissingPackageJsons(pkgs, rootVersion, log);
  await updateGitignore(generatedRepoRels, log);
}

async function writeWorkspaceFile(pkgs, log) {
  const dirs = pkgs.map((p) => p.normalizedRepoRelativeDir).sort();
  const packagesBlock = `packages:\n${dirs.map((d) => `  - '${d}'`).join('\n')}`;
  const settingsBlock = await renderPnpmSettings();
  const next = `${HEADER}\n${packagesBlock}\n\n${settingsBlock}\n`;

  const current = await readIfExists(WORKSPACE_PATH);
  if (current !== next) {
    await Fsp.writeFile(WORKSPACE_PATH, next);
    log.warning('updated pnpm-workspace.yaml');
  }
}

/**
 * Mirrors package.json "pnpm" (overrides + build allowlist) plus the behavioral
 * install settings into pnpm-workspace.yaml. package.json stays the authored
 * source of truth (sorted by sort-package-json, read by dependency tooling);
 * this is the only place pnpm 11 actually reads them from.
 */
async function renderPnpmSettings() {
  const { pnpm = {} } = JSON.parse(await Fsp.readFile(ROOT_PACKAGE_JSON_PATH, 'utf8'));
  const blocks = [INSTALL_SETTINGS];

  // pnpm 11 replaced onlyBuiltDependencies/ignoredBuiltDependencies with a single
  // allowBuilds map ({ name: true|false }). Listing both keeps every build-script
  // dependency explicitly reviewed, so pnpm never appends placeholders (which would
  // fail bootstrap's changed-files check).
  const allowBuilds = new Map();
  for (const name of pnpm.onlyBuiltDependencies ?? []) allowBuilds.set(name, true);
  for (const name of pnpm.ignoredBuiltDependencies ?? []) allowBuilds.set(name, false);
  if (allowBuilds.size) {
    const entries = [...allowBuilds.keys()].sort();
    blocks.push(
      ['allowBuilds:', ...entries.map((name) => `  ${yaml(name)}: ${allowBuilds.get(name)}`)].join(
        '\n'
      )
    );
  }

  const overrides = pnpm.overrides ?? {};
  const overrideKeys = Object.keys(overrides).sort();
  if (overrideKeys.length) {
    blocks.push(
      ['overrides:', ...overrideKeys.map((k) => `  ${yaml(k)}: ${yaml(overrides[k])}`)].join('\n')
    );
  }

  return blocks.join('\n');
}

// Single-quote every key/value: override keys/values carry @, >, <, :, $ and
// spaces that YAML would otherwise mis-parse. Only '' needs escaping inside.
function yaml(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

/** @returns {Promise<string[]>} repo-relative paths of packages we generated a package.json for */
async function synthesizeMissingPackageJsons(pkgs, rootVersion, log) {
  const generatedRepoRels = [];
  let written = 0;
  await Promise.all(
    pkgs.map(async (p) => {
      // A package "ships" its own package.json only if it's a real, source-controlled one.
      // Files we previously generated carry a sentinel and must be (re)managed by us.
      if (p.pkg && !isGeneratedManifest(p.pkg)) return;
      generatedRepoRels.push(p.normalizedRepoRelativeDir);
      const path = Path.resolve(p.directory, 'package.json');
      const contents = generatedPackageJson(p.id, rootVersion);
      if ((await readIfExists(path)) !== contents) {
        await Fsp.writeFile(path, contents);
        written += 1;
      }
    })
  );
  if (written) {
    log.warning(`generated ${written} package.json file(s) for workspace packages`);
  }
  return generatedRepoRels.sort();
}

function isGeneratedManifest(pkg) {
  return !!pkg && pkg.kbnGenerated === true;
}

async function updateGitignore(generatedRepoRels, log) {
  const block = [
    GITIGNORE_START,
    ...generatedRepoRels.map((d) => `/${d}/package.json`),
    GITIGNORE_END,
  ].join('\n');

  const current = (await readIfExists(GITIGNORE_PATH)) ?? '';
  const re = new RegExp(`${GITIGNORE_START}[\\s\\S]*?${GITIGNORE_END}`);
  const next = re.test(current)
    ? current.replace(re, block)
    : `${current.replace(/\n*$/, '')}\n\n${block}\n`;

  if (next !== current) {
    await Fsp.writeFile(GITIGNORE_PATH, next);
    log.warning('updated .gitignore with generated package.json paths');
  }
}

function generatedPackageJson(id, version) {
  return `${JSON.stringify(
    {
      name: id,
      version,
      private: true,
      license: 'Elastic-2.0',
      kbnGenerated: true,
    },
    null,
    2
  )}\n`;
}

async function readIfExists(path) {
  try {
    return await Fsp.readFile(path, 'utf8');
  } catch {
    return undefined;
  }
}

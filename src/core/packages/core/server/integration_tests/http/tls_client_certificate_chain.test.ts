import { readFileSync } from 'fs';
import https from 'https';
import http2 from 'http2';
import type { SecureVersion } from 'tls';
import { of } from 'rxjs';
import {
  CA_CERT_PATH,
  KBN_CERT_PATH,
  KBN_KEY_PATH,
  PKI_INTERMEDIATE_CA_CERT_PATH,
  PKI_INTERMEDIATE_CA_2_CERT_PATH,
  PKI_INTERMEDIATE_CLIENT_CERT_PATH,
  PKI_INTERMEDIATE_CLIENT_KEY_PATH,
  PKI_INTERMEDIATE_2_CLIENT_CERT_PATH,
  PKI_INTERMEDIATE_2_CLIENT_KEY_PATH,
  PKI_UNTRUSTED_CA_CERT_PATH,
  PKI_UNTRUSTED_CLIENT_CERT_PATH,
  PKI_UNTRUSTED_CLIENT_KEY_PATH,
} from '@kbn/dev-utils';
import { Router } from '@kbn/core-http-router-server-internal';
import {
  HttpServer,
  HttpConfig,
  config as httpConfig,
  cspConfig,
  externalUrlConfig,
  permissionsPolicyConfig,
} from '@kbn/core-http-server-internal';
import { mockCoreContext } from '@kbn/core-base-server-mocks';
import { createTestEnv, getEnvOptions } from '@kbn/config-mocks';

const options = getEnvOptions();
options.cliArgs.dev = false;
const env = createTestEnv({ envOptions: options });

const CSP_CONFIG = cspConfig.schema.validate({});
const EXTERNAL_URL_CONFIG = externalUrlConfig.schema.validate({});
const PERMISSIONS_POLICY_CONFIG = permissionsPolicyConfig.schema.validate({});
const enhanceWithContext = (fn: (...args: any[]) => any) => fn.bind(null, {});

const HOST = '127.0.0.1';
const PORT = 10002;
const REQUESTS_PER_CONNECTION = 3;

const ROOT_CA_CN = 'Elastic Certificate Tool Autogenerated CA';
const INTERMEDIATE_CA_CN = 'Kibana PKI Test Intermediate CA';
const INTERMEDIATE_CA_2_CN = 'Kibana PKI Test Intermediate CA 2';

const read = (path: string) => readFileSync(path, 'utf8');

interface ChainResponse {
  authorized: boolean | undefined;
  authorizationError: string | undefined;
  chain: string[];
  isChainIncomplete: boolean;
}

interface ClientIdentity {
  cert: string;
  key: string;
}

/** The client sends its leaf certificate followed by whatever intermediates it holds. */
const clientIdentity = (keyPath: string, ...certPaths: string[]): ClientIdentity => ({
  key: read(keyPath),
  cert: certPaths.map(read).join(''),
});

const oneIntermediateClient = clientIdentity(
  PKI_INTERMEDIATE_CLIENT_KEY_PATH,
  PKI_INTERMEDIATE_CLIENT_CERT_PATH,
  PKI_INTERMEDIATE_CA_CERT_PATH
);
const twoIntermediatesClient = clientIdentity(
  PKI_INTERMEDIATE_2_CLIENT_KEY_PATH,
  PKI_INTERMEDIATE_2_CLIENT_CERT_PATH,
  PKI_INTERMEDIATE_CA_2_CERT_PATH,
  PKI_INTERMEDIATE_CA_CERT_PATH
);
const leafOnlyClient = clientIdentity(
  PKI_INTERMEDIATE_CLIENT_KEY_PATH,
  PKI_INTERMEDIATE_CLIENT_CERT_PATH
);
const leafOnlyTwoIntermediatesClient = clientIdentity(
  PKI_INTERMEDIATE_2_CLIENT_KEY_PATH,
  PKI_INTERMEDIATE_2_CLIENT_CERT_PATH
);
/** Sends a complete chain, so the only thing wrong with it is the root. */
const untrustedClient = clientIdentity(
  PKI_UNTRUSTED_CLIENT_KEY_PATH,
  PKI_UNTRUSTED_CLIENT_CERT_PATH,
  PKI_UNTRUSTED_CA_CERT_PATH
);

const ONE_INTERMEDIATE_CHAIN = ['pki_intermediate_client', INTERMEDIATE_CA_CN, ROOT_CA_CN];
const TWO_INTERMEDIATES_CHAIN = [
  'pki_intermediate_2_client',
  INTERMEDIATE_CA_2_CN,
  INTERMEDIATE_CA_CN,
  ROOT_CA_CN,
];

type Protocol = 'http1' | 'http2';

interface ConnectionOptions extends ClientIdentity {
  protocol: Protocol;
  tlsVersion: SecureVersion;
}

/** Sends several requests over a single connection and returns what the server saw for each. */
const requestChainOverOneConnection = async ({
  protocol,
  tlsVersion,
  cert,
  key,
}: ConnectionOptions): Promise<ChainResponse[]> => {
  // The client doesn't need to verify Kibana's certificate for these tests.
  const tlsOptions = {
    cert,
    key,
    minVersion: tlsVersion,
    maxVersion: tlsVersion,
    rejectUnauthorized: false,
  };

  if (protocol === 'http2') {
    const session = http2.connect(`https://${HOST}:${PORT}`, tlsOptions);
    try {
      const responses: ChainResponse[] = [];
      for (let i = 0; i < REQUESTS_PER_CONNECTION; i++) {
        responses.push(await requestChainHttp2(session));
      }
      return responses;
    } finally {
      session.close();
    }
  }

  const agent = new https.Agent({ ...tlsOptions, keepAlive: true, maxSockets: 1 });
  try {
    const responses: ChainResponse[] = [];
    for (let i = 0; i < REQUESTS_PER_CONNECTION; i++) {
      const { reusedSocket, body } = await requestChainHttp1(agent);
      expect(reusedSocket).toBe(i > 0);
      responses.push(body);
    }
    return responses;
  } finally {
    agent.destroy();
  }
};

const requestChainHttp1 = (agent: https.Agent) =>
  new Promise<{ reusedSocket: boolean; body: ChainResponse }>((resolve, reject) => {
    const req = https.get({ host: HOST, port: PORT, path: '/chain', agent }, (res) => {
      let data = '';
      res.setEncoding('utf8');
      res.on('data', (chunk) => (data += chunk));
      res.on('end', () => resolve({ reusedSocket: req.reusedSocket, body: JSON.parse(data) }));
      res.on('error', reject);
    });
    req.on('error', reject);
  });

const requestChainHttp2 = (session: http2.ClientHttp2Session) =>
  new Promise<ChainResponse>((resolve, reject) => {
    const stream = session.request({ ':method': 'GET', ':path': '/chain' });
    let data = '';
    stream.setEncoding('utf8');
    stream.on('data', (chunk) => (data += chunk));
    stream.on('end', () => resolve(JSON.parse(data)));
    stream.on('error', reject);
    stream.end();
  });

const startServer = async (protocol: Protocol, certificateAuthorities: string[]) => {
  const coreContext = mockCoreContext.create();
  const logger = coreContext.logger.get();
  const rawConfig = httpConfig.schema.validate({
    name: 'kibana',
    protocol,
    host: HOST,
    port: PORT,
    ssl: {
      enabled: true,
      certificate: KBN_CERT_PATH,
      key: KBN_KEY_PATH,
      certificateAuthorities,
      clientAuthentication: 'optional',
    },
    shutdownTimeout: '1s',
    restrictInternalApis: false,
  });
  const config = new HttpConfig(
    rawConfig,
    CSP_CONFIG,
    EXTERNAL_URL_CONFIG,
    PERMISSIONS_POLICY_CONFIG
  );
  const server = new HttpServer(coreContext, 'tests', of(config.shutdownTimeout));
  const { registerRouter } = await server.setup({ config$: of(config) });

  const router = new Router('', logger, enhanceWithContext, {
    env,
    versionedRouterOptions: { defaultHandlerResolutionStrategy: 'oldest' },
  });
  router.get(
    { path: '/chain', validate: false, security: { authz: { enabled: false, reason: '' } } },
    async (ctx, req, res) => {
      // Walks the chain the same way the PKI authentication provider does.
      const chain: string[] = [];
      let isChainIncomplete = false;
      let certificate = req.socket.getPeerCertificate(true);
      while (certificate && Object.keys(certificate).length > 0) {
        chain.push(certificate.subject.CN);
        if (certificate === certificate.issuerCertificate) {
          break;
        }
        if (certificate.issuerCertificate === undefined) {
          isChainIncomplete = true;
          break;
        }
        certificate = certificate.issuerCertificate;
      }

      const { authorized, authorizationError } = req.socket;
      const body: ChainResponse = {
        authorized,
        // Typed as `Error`, but Node sets it to an OpenSSL error code string.
        authorizationError: authorizationError ? `${authorizationError}` : undefined,
        chain,
        isChainIncomplete,
      };
      return res.ok({ body });
    }
  );
  registerRouter(router);
  await server.start();

  return server;
};

describe.each<Protocol>(['http1', 'http2'])('TLS client certificate chain (%s)', (protocol) => {
  describe.each<SecureVersion>(['TLSv1.2', 'TLSv1.3'])('%s', (tlsVersion) => {
    describe('server trusts only the root CA', () => {
      let server: HttpServer;

      beforeAll(async () => {
        server = await startServer(protocol, [CA_CERT_PATH]);
      });

      afterAll(async () => {
        await server?.stop();
      });

      it('returns the full chain when the client sends one intermediate', async () => {
        const responses = await requestChainOverOneConnection({
          protocol,
          tlsVersion,
          ...oneIntermediateClient,
        });

        for (const response of responses) {
          expect(response).toEqual({
            authorized: true,
            chain: ONE_INTERMEDIATE_CHAIN,
            isChainIncomplete: false,
          });
        }
      });

      it('returns the full chain when the client sends two intermediates', async () => {
        const responses = await requestChainOverOneConnection({
          protocol,
          tlsVersion,
          ...twoIntermediatesClient,
        });

        for (const response of responses) {
          expect(response).toEqual({
            authorized: true,
            chain: TWO_INTERMEDIATES_CHAIN,
            isChainIncomplete: false,
          });
        }
      });

      it('does not authorize a client that sends only its leaf certificate', async () => {
        const responses = await requestChainOverOneConnection({
          protocol,
          tlsVersion,
          ...leafOnlyClient,
        });

        for (const response of responses) {
          expect(response.authorized).toBe(false);
          expect(response.authorizationError).toBe('UNABLE_TO_VERIFY_LEAF_SIGNATURE');
        }
      });

      it('does not authorize a client certificate from an untrusted root CA', async () => {
        const responses = await requestChainOverOneConnection({
          protocol,
          tlsVersion,
          ...untrustedClient,
        });

        for (const response of responses) {
          expect(response.authorized).toBe(false);
          expect(response.authorizationError).toBe('SELF_SIGNED_CERT_IN_CHAIN');
        }
      });
    });

    describe('server trusts the root and intermediate CAs', () => {
      let server: HttpServer;

      beforeAll(async () => {
        server = await startServer(protocol, [
          CA_CERT_PATH,
          PKI_INTERMEDIATE_CA_CERT_PATH,
          PKI_INTERMEDIATE_CA_2_CERT_PATH,
        ]);
      });

      afterAll(async () => {
        await server?.stop();
      });

      it('returns the full chain when the client sends one intermediate', async () => {
        const responses = await requestChainOverOneConnection({
          protocol,
          tlsVersion,
          ...oneIntermediateClient,
        });

        for (const response of responses) {
          expect(response).toEqual({
            authorized: true,
            chain: ONE_INTERMEDIATE_CHAIN,
            isChainIncomplete: false,
          });
        }
      });

      it('returns the full chain when the client sends two intermediates', async () => {
        const responses = await requestChainOverOneConnection({
          protocol,
          tlsVersion,
          ...twoIntermediatesClient,
        });

        for (const response of responses) {
          expect(response).toEqual({
            authorized: true,
            chain: TWO_INTERMEDIATES_CHAIN,
            isChainIncomplete: false,
          });
        }
      });

      it('returns the full chain when the client sends only its leaf certificate', async () => {
        const responses = await requestChainOverOneConnection({
          protocol,
          tlsVersion,
          ...leafOnlyClient,
        });

        for (const response of responses) {
          expect(response).toEqual({
            authorized: true,
            chain: ONE_INTERMEDIATE_CHAIN,
            isChainIncomplete: false,
          });
        }
      });

      it('returns the full chain when a client two intermediates down sends only its leaf certificate', async () => {
        const responses = await requestChainOverOneConnection({
          protocol,
          tlsVersion,
          ...leafOnlyTwoIntermediatesClient,
        });

        for (const response of responses) {
          expect(response).toEqual({
            authorized: true,
            chain: TWO_INTERMEDIATES_CHAIN,
            isChainIncomplete: false,
          });
        }
      });

      it('does not authorize a client certificate from an untrusted root CA', async () => {
        const responses = await requestChainOverOneConnection({
          protocol,
          tlsVersion,
          ...untrustedClient,
        });

        for (const response of responses) {
          expect(response.authorized).toBe(false);
          expect(response.authorizationError).toBe('SELF_SIGNED_CERT_IN_CHAIN');
        }
      });
    });
  });
});
